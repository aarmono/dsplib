#!/usr/bin/env python3
"""src/v34/v34_hs_states.h (enum V34HsState) from the handshake state-name table of the sources.

The names are the 87 strings of `StateName[87]` (src/v34/v34_init_tables.c, the blob's LOCAL OBJECT in .data, which the blob's v34handshak
prints as "V34HSHAKE: txstate %s=>%s(rx %s, mst %s, ...)").  The enumerator of state N is V34HS_<string>, value N.

  python3 tools/v34_hs_states_gen.py            write src/v34/v34_hs_states.h
  python3 tools/v34_hs_states_gen.py --check    exit 1 if the committed header differs from what the table text gives
                                                (also compares, with the C compiler, that StateName[V34HS_x] is the string x for every x)
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.dirname(HERE)
TABLE = os.path.join(LIB, "src/v34/v34_init_tables.c")
OUT = os.path.join(LIB, "src/v34/v34_hs_states.h")


def table():
    t = open(TABLE).read()
    m = re.search(r"const char \*const StateName\[87\] = \{(.*?)\n\};", t, re.S)
    ents = re.findall(r'/\*\s*(\d+)\s*\*/\s*"([^"]+)"', m.group(1))
    names = []
    for i, (n, s) in enumerate(ents):
        assert int(n) == i, (n, i)
        names.append(s)
    assert len(names) == 87 and len(set(names)) == 87
    return names


def render(names):
    o = []
    o.append("/**")
    o.append(" * @file v34_hs_states.h")
    o.append(" * @brief V34HsState: the 87 states of the V.34 handshake state machine, named after the StateName[87] table of src/v34/v34_init_tables.c.")
    o.append(" *")
    o.append(" * GENERATED by tools/v34_hs_states_gen.py from that table (the strings v34handshak prints in \"V34HSHAKE: txstate %s=>%s(...)\"); do not edit,")
    o.append(" * run the tool (--check verifies this file).")
    o.append(" *")
    o.append(" * The three state words of the handshake object share this value space: obj->txState_ (the transmit state), obj->rxState_ and obj->mst_ (the")
    o.append(" * receive \"microstate\" of the DPSK receiver).  Use the names for those members and for the arguments that carry such a state; the same")
    o.append(" * numbers also occur elsewhere (V34HS_DET_SYNC = 0x29 is also a tone-history index and a bit offset): convert by member, never by value. */")
    o.append("#ifndef V34_HS_STATES_H")
    o.append("#define V34_HS_STATES_H")
    o.append("")
    o.append("enum V34HsState {")
    for i, n in enumerate(names):
        o.append("  V34HS_%s = %d,%s" % (n, i, "  /* 0x%02x */" % i))
    o.append("  V34HS_COUNT = %d" % len(names))
    o.append("};")
    o.append("")
    o.append("#endif /* V34_HS_STATES_H */")
    return "\n".join(o) + "\n"


def selfcheck(names):
    """compile a program that includes the header and the table and compares StateName[V34HS_x] with "x" for every x"""
    src = ['#include <string.h>', '#include "v34/v34_hs_states.h"', 'extern const char *const StateName[87];']
    src.append("int check(void) {")
    for n in names:
        src.append('  if (strcmp(StateName[V34HS_%s], "%s")) return 1;' % (n, n))
    src.append("  return V34HS_COUNT != 87;\n}")
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, "chk.c")
        open(c, "w").write("\n".join(src) + "\n")
        main = os.path.join(d, "main.c")
        open(main, "w").write("int check(void); int main(void){return check();}\n")
        tbl = os.path.join(d, "tbl.c")
        open(tbl, "w").write('#define main_unused\n#include "v34/v34_init_tables.c"\n')
        exe = os.path.join(d, "chk")
        r = subprocess.run(["gcc", "-w", "-I" + os.path.join(LIB, "src"), c, main, tbl, "-o", exe],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print("selfcheck: compile failed (table needs the host build flags?):", r.stderr[:500])
            return None
        return subprocess.run([exe]).returncode == 0


def formatted(text):
    """src/ is clang-formatted (the pre-commit hook): compare / write what the formatter makes of the text, so that --check is not a whitespace check."""
    r = subprocess.run(["clang-format", "--assume-filename=" + OUT], input=text, capture_output=True, text=True, cwd=LIB)
    return r.stdout if r.returncode == 0 and r.stdout else text


def main():
    names = table()
    text = formatted(render(names))
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        ok = cur == text
        print("header %s the table text" % ("matches" if ok else "DIFFERS from"))
        sc = selfcheck(names)
        if sc is not None:
            print("StateName[V34HS_x] == \"x\" for all 87: %s" % ("yes" if sc else "NO"))
            ok = ok and sc
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("wrote", OUT)


main()
