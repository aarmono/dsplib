#!/usr/bin/env python3
"""layout64.py [--check] - generate src/v34/v34_object_layout64.inc: the x86-64 layout asserts of the V.34 module object.

The object (src/v34/v34_object_view.h) has real pointer members, so the compiler computes the x86-64 layout; the i386 offsets are pinned by the
V34VIEW_ASSERT blocks of the generated headers.  This tool pins the native layout the same way: sizeof(V34Obj), the base and size of every sub-object,
and the offset of every pointer member (the 8-byte slots whose placement moves everything behind them).  The numbers come from compiling a probe with
`gcc -m64` against the generated headers (-DV34L64_PROBE keeps the probe from including the file being generated), so the file records what the compiler
makes of the declarations and the build fails when a declaration changes the native layout without regenerating it (`sh tools/gen_views.sh`).

  python3 tools/layout64.py            write src/v34/v34_object_layout64.inc
  python3 tools/layout64.py --check    exit 1 when the file differs from a fresh one
Run from the repository root (tools/gen_views.sh does).
"""
import os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = 'src/v34/v34_object_layout64.inc'
VIEW = 'src/v34/v34_object_view.h'
SUB = 'src/v34/v34_subobjects.h'


def struct_bodies(text):
    """name -> list of member declaration lines, for `typedef struct {...} Name;` and `typedef struct tag {...} Name;`"""
    out = {}
    for m in re.finditer(r'typedef struct(?: \w+)? \{\n(.*?)\n\} (\w+);', text, re.S):
        out[m.group(2)] = m.group(1).split('\n')
    return out


def members(lines):
    """(type text, name) of the members declared in a struct body (one declaration per line; `type name; /* comment */`)"""
    for l in lines:
        l = re.sub(r'/\*.*?\*/', '', l).strip()
        m = re.match(r'^(.*?[\s*])(\w+)(\[[^\]]*\])?;$', l)
        if m and not l.startswith('#'):
            yield m.group(1).strip(), m.group(2), m.group(3)


def collect():
    sub_text = open(os.path.join(ROOT, SUB)).read()
    view_text = open(os.path.join(ROOT, VIEW)).read()
    bodies = struct_bodies(sub_text)
    obj = struct_bodies(view_text)['V34Obj']
    # embedded sub-objects: (member path, struct name)
    subs = []
    ptrs = []

    def walk(struct_lines, prefix):
        for ty, name, arr in members(struct_lines):
            if arr is None and ty.endswith('*'):
                ptrs.append(prefix + name)
            elif arr is None and ty in bodies:
                subs.append((prefix + name, ty))
                walk(bodies[ty], prefix + name + '.')
            elif arr is None and ty.startswith('union') is False and ty == 'V34Echo':
                pass
    walk(obj, '')
    return subs, ptrs


def generate():
    subs, ptrs = collect()
    probe = ['#define V34L64_PROBE 1', '#include <stddef.h>', '#include <stdio.h>', '#include "v34_object_view.h"', 'int main(void) {',
             '  printf("size %zu\\n", sizeof(V34Obj));']
    for path, st in subs:
        probe.append('  printf("sub %s %%zu %%zu\\n", offsetof(V34Obj, %s), sizeof(%s));' % (path, path, st))
    for p in ptrs:
        probe.append('  printf("ptr %s %%zu\\n", offsetof(V34Obj, %s));' % (p, p))
    probe.append('  return 0; }')
    tmp = tempfile.mkdtemp(prefix='layout64.', dir=os.environ.get('TMPDIR'))
    try:
        src = os.path.join(tmp, 'p.c')
        open(src, 'w').write('\n'.join(probe) + '\n')
        exe = os.path.join(tmp, 'p')
        subprocess.run(['gcc', '-m64', '-w', '-I', os.path.join(ROOT, 'src/v34'), '-I', os.path.join(ROOT, 'src'), '-o', exe, src], check=True)
        res = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split('\n')
    finally:
        subprocess.run(['rm', '-r', tmp])
    size = None
    subv, ptrv = [], []
    for l in res:
        p = l.split()
        if not p:
            continue
        if p[0] == 'size':
            size = int(p[1])
        elif p[0] == 'sub':
            subv.append((p[1], int(p[2]), int(p[3])))
        elif p[0] == 'ptr':
            ptrv.append((p[1], int(p[2])))
    st = dict(subs)
    o = ['/* GENERATED by tools/layout64.py: do not edit.  x86-64 layout asserts of the V.34 module object V34Obj (the generated view v34_object_view.h, which includes',
         ' * this file at its end): the object size, the base and size of every embedded sub-object and the offset of every pointer member.  The 32-bit offsets are the',
         ' * V34VIEW_ASSERT blocks of the generated headers; here the compiler\'s native layout (8-byte pointers, natural alignment) is pinned.  Regenerate with',
         ' * `sh tools/gen_views.sh` after a change of a declaration; the numbers are probed with gcc -m64 (-DV34L64_PROBE excludes this file from the probe). */',
         '#if defined(__x86_64__) && !defined(V34L64_PROBE)',
         'V34VIEW_ASSERT(sizeof(V34Obj) == 0x%x, "sizeof V34Obj (x86-64)");' % size]
    line = []
    for path, off, sz in subv:
        line.append('offsetof(V34Obj, %s) == 0x%x && sizeof(%s) == 0x%x' % (path, off, st[path], sz))
    for i in range(0, len(line), 2):
        o.append('V34VIEW_ASSERT(' + ' &&\n                   '.join(line[i:i + 2]) + ',\n               "sub-objects: base and size (x86-64)");')
    line = ['offsetof(V34Obj, %s) == 0x%x' % (p, off) for p, off in ptrv]
    for i in range(0, len(line), 3):
        o.append('V34VIEW_ASSERT(' + ' &&\n                   '.join(line[i:i + 3]) + ',\n               "pointer members (x86-64)");')
    o.append('#endif')
    return '\n'.join(o) + '\n'


def main():
    os.chdir(ROOT)
    text = generate()
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            print('%s differs from the freshly generated one (run tools/gen_views.sh)' % OUT, file=sys.stderr)
            sys.exit(1)
        print('layout64 up to date')
        return
    open(OUT, 'w').write(text)
    print('wrote %s' % OUT)


if __name__ == '__main__':
    main()
