#!/usr/bin/env python3
"""src/v8/v8_status.h (enum V8Status) from the v8StatusName[19] table of the sources.
The same header also gets enum V8CtrlType from the v8ControlName[11] table (static in src/v8/v8.c; V8Control prints it).

The 19 strings of v8StatusName (the blob's GLOBAL table, .rodata 0x53c0; src/v8/dp_v8.c has it as an exported array, src/v8/v8.c as a static copy
used by V8Process' debug print) are the identifiers: the enumerator of status N is the string N itself (V8_INIT = 0 ... V8_OK = 13 ... V8_LAST_ENUM = 18).

  python3 tools/v8_status_gen.py            write src/v8/v8_status.h
  python3 tools/v8_status_gen.py --check    exit 1 if the header differs from what the table text gives, or if the two table copies differ
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.dirname(HERE)
OUT = os.path.join(LIB, "src/v8/v8_status.h")


def table(path, tname="v8StatusName", n=19):
    t = open(os.path.join(LIB, path)).read()
    m = re.search(tname + r"\[%d\] = \{(.*?)\};" % n, t, re.S)
    names = re.findall(r'"([^"]+)"', m.group(1))
    assert len(names) == n and len(set(names)) == n, path
    return names


def render(names, ctrl):
    o = []
    o.append("/* GENERATED by tools/v8_status_gen.py from the v8StatusName[19] table (src/v8/dp_v8.c: the names of the V.8 states, the strings V8Process prints in")
    o.append(" * \"V8: State changed from %s to %s\"); do not edit, run the tool (--check verifies this file).  The value V8Process returns and stores in V8Obj::lastStatus,")
    o.append(" * and dp_v8.c's v8_process switches on.  It also holds enum V8CtrlType, from the v8ControlName[11] table (src/v8/v8.c). */")
    o.append("#ifndef V8_STATUS_H")
    o.append("#define V8_STATUS_H")
    o.append("")
    o.append("enum V8Status")
    o.append("{")
    for i, n in enumerate(names):
        o.append("  %s = %d%s" % (n, i, "," if i + 1 < len(names) else ""))
    o.append("};")
    o.append("")
    o.append("/* The control types of V8Control(v8, ctrlType): the strings of the v8ControlName[11] table (static in src/v8/v8.c), which V8Control prints in")
    o.append(" * \"V8: V8Control called - control type is %s\".  Only the first three are acted on; the others make V8Control return -1. */")
    o.append("enum V8CtrlType")
    o.append("{")
    for i, n in enumerate(ctrl):
        o.append("  %s = %d%s" % (n, i, "," if i + 1 < len(ctrl) else ""))
    o.append("};")
    o.append("")
    o.append("#endif /* V8_STATUS_H */")
    return "\n".join(o) + "\n"


def main():
    names = table("src/v8/dp_v8.c")
    ok = True
    if table("src/v8/v8.c") != names:
        print("the two copies of v8StatusName (dp_v8.c, v8.c) differ")
        ok = False
    ctrl = table("src/v8/v8.c", "v8ControlName", 11)
    text = render(names, ctrl)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("header DIFFERS from the table text")
            ok = False
        else:
            print("header matches the table text")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("wrote", OUT)


main()
