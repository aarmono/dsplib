#include "pcm_leaf_classes.h"         /* V90RDetector */
#include "pcm_parameters.h"           /* V90Parameters */
#include "v90_mp.h"                   /* V90MP */
#include "v90_cp.h"                   /* V90CP */
#include "v92_cp.h"                   /* V90MappingParams */
#include "v90_connection_evaluator.h" /* V90ConnectionEvaluator */
#include "v90_adid.h"                 /* V90AutoDigitalImpDetector */
#include "v90_mapper.h"               /* V90Demapper */
#include "v90_phase4_modulator.h"     /* V90Phase4Modulator */
#include "v90_phase3_demod.h"         /* V90Phase3Demodulator */

/** @brief States of the phase 4 receive state machine (the value of V90Phase4Demodulator::state_); see the table in the file header. */
enum Phase4DemodulatorState
{
  P4D_WAIT_RI = 0,       ///< wait for Ri
  P4D_WAIT_RI_NOT = 1,   ///< wait for RiNot
  P4D_TRN2D_ENTRY = 2,   ///< TRN2d known data, entry (the next call moves to P4D_TRN2D_KNOWN)
  P4D_TRN2D_KNOWN = 3,   ///< TRN2d known data (linear mapping study)
  P4D_WAIT_CP = 4,       ///< V.92: wait for the CP
  P4D_WAIT_MP = 5,       ///< V.90: wait for the MP
  P4D_WAIT_ED = 6,       ///< V.90: wait for Ed
  P4D_B1D = 7,           ///< B1d (counts the descrambled bits)
  P4D_TERMINATED = 8,    ///< phase 4 done, no output
  P4D_TRN2D_DD = 9,      ///< TRN2d DD: wait for RdNot
  P4D_SILENCE_WAIT = 10, ///< RRN silence: wait before the echo calculation
  P4D_ECHO_BEFORE = 11,  ///< RRN silence: error energy before the echo cancellation
  P4D_ECHO_WAIT = 12,    ///< RRN silence: wait for the echo canceller
  P4D_ECHO_AFTER = 13,   ///< RRN silence: error energy after the echo cancellation
  P4D_WAIT_RT = 14,      ///< wait for Rt
  P4D_WAIT_RT_NOT = 15,  ///< wait for RtNot
  P4D_WAIT_RF_NOT = 16   ///< V.92: wait for RfNot
};

/** @brief Phase 4 receive state machine; see the file header. */
class V90Phase4Demodulator
{
public:
  /**
   * @brief Construct the object: the embedded modulator and detectors, then the borrowed-object pointers.
   * @param mp1      mapping parameters of the TRN2d design (borrowed)
   * @param mp2      mapping parameters of the data constellation (borrowed)
   * @param dem      demapper (borrowed)
   * @param cp       V.92 CP structure (borrowed)
   * @param mp       V.90 MP structure (borrowed)
   * @param descr    descrambler of the received bits (borrowed)
   * @param ce       connection evaluator (borrowed; its rrnSilence_ is read)
   * @param p        parameter block (borrowed)
   * @param p3       phase 3 demodulator (borrowed)
   * @param adid     automatic digital impairment detector (borrowed)
   * @param session  0 for V.90, non-zero for V.92
   * @note The embedded V90Phase4Modulator gets the two mapping parameter pointers in the opposite order to this constructor's arguments (mp2, then mp1).
   * @warning All other members stay uninitialised until reset().
   */
  V90Phase4Demodulator(V90MappingParams* mp1, V90MappingParams* mp2, V90Demapper* dem, V90CP* cp, V90MP* mp, Descrambler<unsigned char, int>* descr,
                       V90ConnectionEvaluator* ce, V90Parameters* p, V90Phase3Demodulator* p3, V90AutoDigitalImpDetector* adid, unsigned session);
  /** @brief Destroy the object (destroys `rf_`, `r_` and `mod_` in that order; nothing is released, all pointers are borrowed). */
  ~V90Phase4Demodulator();
  /** @brief Set the V.90 / V.92 session flag of this object and of the embedded modulator. */
  void setSessionFlag(unsigned f);
  /** @brief Enter state P4D_WAIT_CP (V.92) and restart the symbol counter. */
  void enterWaitForCP();
  /** @brief Enter state P4D_WAIT_MP (V.90) and restart the symbol counter. */
  void enterWaitForMP();
  /** @brief Enter state P4D_WAIT_ED (V.90) and restart the symbol counter. */
  void enterWaitForEd();
  /** @brief Reset the Rt / Rf detectors for the RRN (remote retrain) wait. */
  void resetRRNDetector();
  /** @brief Run the Rd detector on one symbol; on detection enter P4D_TRN2D_DD. @return 1 when Rd was detected, else 0 */
  int detectRRN(short x);
  /** @brief Set the flags that say a retrain-request (RRN) exchange is pending and clear the CP bookkeeping. */
  void resetBeforRRN();
  /** @brief Run the Rf detector on one symbol; on detection enter P4D_WAIT_RF_NOT. @return 1 when Rf was detected, else 0 */
  int detectFPE(short x);
  /** @brief Known-data demodulation helper for TRN2d; no caller in the library. */
  short trn2dKnownDemod(short x);
  /**
   * @brief Reset the machine to a starting state and run `settleCount` decisions on a zero symbol.
   * @param code         G.711 code passed to the embedded modulator
   * @param st           starting state
   * @param settleCount  number of getV92Decision(0) / getV90Decision(0) calls made after the reset
   * @param quickConnect non-zero selects the quick-connect length of the TRN2d data limit
   * @note The current `session_` selects the CP (V.92) or MP (V.90) that is reset.
   */
  void reset(unsigned char code, Phase4DemodulatorState st, unsigned settleCount, unsigned quickConnect);
  /** @brief Run one symbol through the state machine. @return the decision symbol (getV92Decision() when `session_` is set, else getV90Decision()) */
  short getDecision(short x);
  /** @brief V.90 state machine, one symbol (v90_phase4_demod_decisions.cpp). @return the decision symbol */
  short getV90Decision(short x);
  /** @brief V.92 state machine, one symbol (v90_phase4_demod_decisions.cpp). @return the decision symbol */
  short getV92Decision(short x);

public:
  unsigned session_;         ///< 0 for V.90, non-zero for V.92
  V90Parameters* params_;    ///< parameter block (borrowed)
  unsigned char code_;       ///< G.711 code handed to the embedded modulator by reset()
  unsigned char pad9_[3];    ///< padding, never accessed
  V90MappingParams* mp1_;    ///< mapping parameters of the TRN2d design (borrowed)
  V90MappingParams* mp2_;    ///< mapping parameters of the data constellation (borrowed)
  V90CP* cp_;                ///< V.92 CP structure (borrowed)
  V90MP* mp_;                ///< V.90 MP structure (borrowed)
  V90Phase3Demodulator* p3_; ///< phase 3 demodulator (borrowed)
  unsigned state_;           ///< current state (Phase4DemodulatorState)
  unsigned cnt_;             ///< symbols counted in the current state (incremented before each dispatch)
  unsigned event_;           ///< output marker for V90Demodulator::progress() (V90DemodState); cleared at the start of every decision
  unsigned limit_;           ///< length in symbols of the TRN2d data (known-data states); event at limit_ / 2 and at limit_
  unsigned char cpSeen_;     ///< V.92: an SUV / SUVt frame was seen in the wait for the CP (an Ed is only accepted after that)
  unsigned char pad31_[3];   ///< padding, never accessed
  unsigned quickConnect_;    ///< reset() argument; selects the quick-connect TRN2d data limit and linear mapping study length
  unsigned rtPending_;       ///< Rt not yet seen; set by reset() / resetBeforRRN() / detectRRN(), cleared when Rt is detected
  unsigned rrnPending_;      ///< a retrain-request exchange is pending; set by detectRRN() (V.90) / resetBeforRRN(), cleared by reset() and at the end of B1d
  unsigned rrnSilence_;      ///< copy of V90ConnectionEvaluator::rrnSilence_ (stored by V90Demodulator::progress(), cleared by reset())
  unsigned answerDue_;       ///< V.92 RRN: the answer is still to be sent (set from a short CP frame)
  unsigned answerSent_;      ///< V.92 RRN: the answer was sent already (set at the first Ed of the RRN)
  unsigned w4c_;             ///< copy of V90CP::wCa0_ taken at a short CP frame; non-zero selects the wait for Rt instead of the silence wait
  V90Phase4Modulator mod_;   ///< the far end's signal, used for the known-data comparison
  V90RDetector r_;           ///< Ri / Rd / Rt detector
  V90RDetector rf_;          ///< Rf detector
  V90Demapper* dem_;         ///< demapper (borrowed)
  Descrambler<unsigned char, int>* descr_; ///< descrambler of the received bits (borrowed)
  unsigned char buf_[1176];                ///< output bytes of V90Demapper::process() for one symbol
  unsigned nBytes_;                        ///< number of valid bytes in buf_
  V90ConnectionEvaluator* ce_;             ///< connection evaluator (borrowed)
  unsigned w34fc_;                         ///< V.92: word 0 of mp1_ stored by reset(); not read in this class
  unsigned b1dZeros_;                      ///< B1d: zero bits seen after the start-up delay
  unsigned b1dBits_;                       ///< B1d: descrambled bits counted
  float echoBefore_;                       ///< RRN silence: error energy accumulator, then the mean, before the echo cancellation
  float echoAfter_;                        ///< RRN silence: the same after the echo cancellation
  unsigned keepRate_;                      ///< set when the SCR echo energy exceeds the keep-rate threshold; cleared by reset()
  V90AutoDigitalImpDetector* adid_;        ///< automatic digital impairment detector (borrowed)
  unsigned studyEnd_;                      ///< symbol count at which the demapper's linear mapping study is switched on in the TRN2d known-data states
};

typedef V90Phase4Demodulator P37_V90Phase4Demodulator;

