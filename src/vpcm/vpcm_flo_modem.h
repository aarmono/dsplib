/**
 * @file vpcm_flo_modem.h
 * @brief VPcmFloModem: the V.90 / V.92 PCM modem engine that sits behind the V.34 module object.
 *
 * VPcmFloModem is the one object a V.34 session (tagV34Object::ctx_) owns while it runs a V.90 or V.92 PCM connection.  It embeds the transmit and
 * receive halves of both standards and the helpers around them, and keeps the bookkeeping that ties them to the V.34 handshake (CP / CPnot frame
 * buffers, phase 2 information records, quick-connect line-verification state).  Every region of the object is a real member; this header is the
 * only definition of the class (vpcm_flo_modem_run.cpp, vpcm_flo_modem.cpp, vpcm_progress.cpp and vpcm_session_wrappers.cpp all compile against it).
 *
 * Embedded sub-objects, constructed in this order and destroyed in reverse: tagV90DILdescriptor dil_, V90Modem v90_, V92Modem v92_, V92EchoCanceller
 * ec_, ANSamToneDetector ansam_, SineWave<float,float> sine_ and GenericIIR<float,double> iir_.  The member order fixes the 32-bit layout (sizeof
 * 0x7f68, the size VPCMXF_Create allocates); vpcm_flo_modem_layout.inc, generated by tools/layout_gen.py, asserts it.
 *
 * Entry points (definitions):
 * - vpcm_flo_modem_run.cpp: v90RunDemodulator() (digital side, receive) and runPcmModem() (V.92 analog side), the two per-block drivers.
 * - vpcm_flo_modem.cpp: constructor / destructor, the CP and Ja bit sources (getV90JaBits(), getV90CpBits()), session set-up and reset
 *   (setPcmSessionType(), externalReset(), setPhaseIIinfo(), getUinfoValue(), vPcmResetPhase3Modem(), enterPhase3()), the visual diagnostics
 *   getters and the quick-connect line verification (qcLineVerification()).
 *
 * The V.34 module entry points the engine calls (VPcmV34* / V34XF_*, declared in vpcm_v34_api.h) take the V.34 context ctx_ as first argument.
 */
#ifndef VPCM_FLO_MODEM_H
#define VPCM_FLO_MODEM_H

#include "core/dsp_cxx.h"
#include "dsp/dsp_float_filters.h"  /* GenericIIR<float,double> */
#include "dsp/dsp_window_fft_psd.h" /* SineWave<float,float> */
#include "dsp/dsp_tone_detectors.h" /* ANSamToneDetector */
#include "pcm_modem.h"              /* V90Modem, V92Modem and everything they include (V90Modulator / V92Modulator / V90Demodulator ...) */
#include "v92_echo_canceller.h"     /* V92EchoCanceller */
#include "v92_phase4_modulator.h"   /* V92Phase4Modulator */
#include "v90_phase3_demod.h"       /* V90Phase3Demodulator (verify_, enterWaitForANSpcmDrop) */
#include "v90_equalizer.h"          /* V90Equalizer (linLen_ ...) */

/** @brief One equalizer / constellation diagnostic point: two 32-bit integers. */
struct int_complex
{
  int re_;
  int im_;
};

/*
 * The phase 2 information records that V90Modem::info_ / V92Modem::info_ point at are the classes V90Phase2Info / V92Phase2Info.  The View names are
 * aliases of them (one definition), so the array pointers are real pointers at either word size.
 */
typedef V90Phase2Info V90Phase2InfoView;
typedef V92Phase2Info V92Phase2InfoView;

/**
 * @brief The V.90 / V.92 PCM modem engine: both standards' halves plus the CP / phase 2 bookkeeping shared with the V.34 module.
 */
class VPcmFloModem
{
public:
  /**
   * @brief Build the engine and all embedded sub-objects.
   * @param ctx    the V.34 context (tagV34Object) that owns this engine; stored in ctx_
   * @param side   which end of the link this is (analog side or digital side)
   * @param params the modem parameter block, shared with both embedded modems
   * @param blk    block length in samples
   * @param mode90 computational mode of the V.90 half
   * @param mode92 computational mode of the V.92 half
   */
  VPcmFloModem(void* ctx, V90ModemSide side, _tagModemParameters* params, unsigned blk, V90ComputationalMode mode90, V92ComputationalMode mode92);
  ~VPcmFloModem();

  /**
   * @brief Run one block of the digital-side (V.90 receive) engine.
   * @param in    input samples, n floats
   * @param n     block length in samples
   * @param bits  receives the demodulated bits
   * @param nBits receives the number of bits written to `bits`
   * @return session event for VPcmV34Progress(): 0 nothing, 1 hand over to the V.34 handshake (state 3), 2 data phase, 3 data phase with
   *         error-correcting rate renegotiation, 5 retrain, 7 drop to V.34, 8 end of session
   */
  int v90RunDemodulator(float* in, unsigned n, int* bits, int* nBits);

  /**
   * @brief Run one block of the analog-side (V.92) engine: echo canceller, V.90 receive half, V.92 transmit half.
   * @param in     input samples, n floats
   * @param out    receives the n transmit samples
   * @param n      block length in samples
   * @param bits   receives the demodulated bits
   * @param nBits  receives the number of bits written to `bits`
   * @param bits2  receives the bits consumed by the V.92 transmit half
   * @param nBits2 receives the number of bits written to `bits2`
   * @return session event, as for v90RunDemodulator(), plus 6 for a fallback to V.90
   */
  int runPcmModem(float* in, float* out, unsigned n, int* bits, int* nBits, int* bits2, int* nBits2);

  /* Setters and helpers with no caller inside the library (the engine drives the same members itself). */
  void setTerminateJaFlag(unsigned char f);          ///< set jaFlag_
  void setTerminateCpFlag(unsigned char f);          ///< set cpFlag_
  void setTerminateCpNotFlag(unsigned char f);       ///< set cpnotFlag_
  void setMinNofTransmitSequences(unsigned short n); ///< set minTxSeq_ and restart the CP sequence counter
  void setNofBitsPhase4(unsigned constel);           ///< nofBitsPhase4_ = 2 for constellation 0, else 4
  void resetBitPointer();                            ///< clear the bit pointer, the Ja / CP / CPnot flags and the sequence counter

  /** @brief Next two bits of the CPnot frame as a Ja word.  @param out receives the bits  @return 1 once the Ja transmission is to end, else 0 */
  int getV90JaBits(short* out);

  /** @brief Next nofBitsPhase4_ bits of the CP frame.  @param out receives the bits  @return 1 when the CPnot transmission is to end, else 0 */
  int getV90CpBits(short* out);

  void setV34BaudForV90();       ///< v34Flags_ = {1, 0, 1, 1, 1, 0}
  void setV34BaudForV34();       ///< v34Flags_ = {1, 0, 1, 1, 1, 1}
  void internalReset();          ///< clear the session state (the same clearing enterPhase3() does)
  void copyMpInfoForInterface(); ///< copy the received MP fields into mpB_ / mpRate2_ / mpH_

  /** @brief Select a V.90 (0) or V.92 (non-zero) session; updates v92Session_, the local V.92 capability and the V.90 modem's session flag. */
  void setPcmSessionType(int session);

  /** @brief Re-initialise the parameters and the session state for a new V.34 session. */
  void externalReset();

  /**
   * @brief Fill the phase 2 information records from the V.34 INFO0 words and publish the uinfo / L2 arrays.
   * @param info0 the V.34 INFO0 word block (V34XF_GetInfo0BitsPtr())
   * @param rtd   round-trip delay estimate from the V.34 module
   */
  void setPhaseIIinfo(int* info0, int rtd);

  /**
   * @brief Compute the L2 probing levels from the V.34 probe results and hand over the phase 2 information.
   * @param x non-zero skips the L2 computation
   * @return the uinfo value from the parameter block, or 0 when dropping to V.34
   */
  int getUinfoValue(short x);

  /** @brief Reset both modems, the echo canceller and the probing tone for a new phase 3. */
  void vPcmResetPhase3Modem();

  /** @brief Enter phase 3: clear the session state, restart the demodulator and pack the DIL descriptor into cpnotFrame_. */
  void enterPhase3();

  /* Visual diagnostics: write up to `max` points to `out` and return how many were written. */
  int getConstellation(int_complex* out, unsigned long max);   ///< constellation points of the last block
  int getLinearEqualizer(int_complex* out, unsigned long max); ///< linear equalizer taps, scaled by 10000, as imaginary parts
  int getDFE(int_complex* out, unsigned long max);             ///< decision-feedback equalizer taps, scaled by 10000, as imaginary parts

  /**
   * @brief One block of the quick-connect line verification: receive the ANSpcm, then send the TONEq tone and silence.
   * @param in     input samples, n floats
   * @param out    receives the n output samples
   * @param n      block length
   * @param bits   receives the demodulated bits
   * @param nBits  set to 0 on return
   * @param bits2  unused
   * @param nBits2 set to 0 on return
   * @return 1 when the verification is over and the session moves to phase 2, else 0
   */
  int qcLineVerification(float* in, float* out, unsigned n, int* bits, int* nBits, int* bits2, int* nBits2);

public:
  void* ctx_;                     ///< the V.34 context (tagV34Object) that owns this engine
  tagV90DILdescriptor dil_;       ///< DIL descriptor exchanged in phase 3
  uint8_t v34Flags_[6];           ///< V.34 rate flags for the V.34 side: {1, 0, 1, 1, 1, last}; last is 1 after a drop to V.34
  uint8_t pad21d_;                ///< alignment
  short cpnotFrame_[2700];        ///< CPnot (or Ja) frame bits, one per element, built by V90CPPacker / DILdescriptorPacker
  uint16_t cpnotLen_;             ///< number of valid bits in cpnotFrame_
  uint16_t bitPtr_;               ///< read position in the CP / CPnot frame being transmitted
  uint8_t trainConstel_;          ///< training constellation size from Jd (0 = 4 points, 1 = 16 points)
  uint8_t rrnConstel_;            ///< rate-renegotiation constellation size from Jd
  uint8_t localRrn_;              ///< set while a locally initiated rate renegotiation is pending
  uint8_t dropToV34_;             ///< set when the demodulator asked to drop to V.34
  uint8_t clearDown_;             ///< clear-down bit placed in the CP
  uint8_t pad173f_;               ///< alignment
  int constelCtr_;                ///< running counter that synthesises the real parts of the constellation diagnostic
  uint8_t mpB_[6];                ///< received MP: type, rate, trellis, non-linear, shaping and CP-pack bytes
  uint16_t mpRate2_;              ///< received MP: rate mask doubled
  uint16_t mpH_[6];               ///< received MP: h1 .. h3 real / imaginary halves
  V90Modem v90_;                  ///< the V.90 modem (transmit and receive halves)
  uint8_t state_;                 ///< session state 0 .. 4 (selects the return code of the block drivers)
  uint8_t flag6119_;              ///< set once the data phase was entered; enables restoring the SAS detector on later events
  uint8_t pad611a_[2];            ///< alignment
  uint32_t v92Session_;           ///< 1 for a V.92 session, 0 for V.90
  uint32_t flag6120_;             ///< 1 on the analog side (the side that runs the V.92 transmit half), 0 on the digital side
  V92Modem v92_;                  ///< the V.92 modem (transmit half and phase 4 modulator)
  V92EchoCanceller ec_;           ///< echo canceller of the analog side
  float ecOut_[212];              ///< echo-cancelled block (also read by the V.34 side for its cleaned-sample view)
  ANSamToneDetector ansam_;       ///< ANSam tone detector
  uint32_t qcState_;              ///< quick-connect line verification state: 0 receive ANSpcm, 1 TONEq running, 2 silence after TONEq
  SineWave<float, float> sine_;   ///< TONEq generator of the line verification
  int qcCount_;                   ///< samples since the start of the current line verification stage
  uint32_t qcFlag_;               ///< set when the ANSpcm drop was seen (TONEq is to start or end)
  uint32_t qcStatus_;             ///< channel verification status read from the phase 3 demodulator
  uint32_t pad6fb8_;              ///< alignment
  short cpFrame_[1800];           ///< CP (or CPt) frame bits, one per element, built by V90CPPacker
  uint16_t cpLen_;                ///< number of valid bits in cpFrame_
  uint8_t jaFlag_;                ///< the Ja transmission is to end
  uint8_t cpFlag_;                ///< the CP has been built and the CPnot is to follow
  uint8_t cpnotFlag_;             ///< the CPnot transmission is to end
  uint8_t cpnotCopied_;           ///< cpnotFrame_ has been copied into cpFrame_ for transmission
  uint8_t nofBitsPhase4_;         ///< CP bits per call: 2 for constellation 0, else 4
  uint8_t pad7dd3_;               ///< alignment
  uint16_t cpSeqCnt_;             ///< number of complete CP sequences sent
  uint16_t minTxSeq_;             ///< minimum number of CP sequences before moving on to the CPnot
  uint32_t uinfoA_[21];           ///< uinfo array published through the phase 2 info records (zeroed by getUinfoValue())
  uint32_t uinfoB_[21];           ///< uinfo array published through the phase 2 info records (zeroed by getUinfoValue())
  float l2_[21];                  ///< L2 probing levels in dB (21 of the 25 probe values)
  uint32_t uinfoD_[21];           ///< uinfo array published through the phase 2 info records (zeroed by getUinfoValue())
  GenericIIR<float, double> iir_; ///< 5-tap notch filter of the entrance filter
  uint8_t entranceFilter_;        ///< entrance filter applied; set by VPcmV34Create() from the parameter block
  uint8_t pad7f5d_[3];            ///< alignment
  uint32_t echoMode_;             ///< echo-silence mode of the analog side (0x21 while echo silence is on)
  uint32_t echoCnt_;              ///< counter that ramps ecOut_[0] during echo silence
};

typedef VPcmFloModem P47_VPcmFloModem;
typedef V90Phase2InfoView P47_V90Info;
typedef V92Phase2InfoView P47_V92Info;

#pragma GCC diagnostic ignored "-Winvalid-offsetof"
#include "vpcm_flo_modem_layout.inc"

#endif /* VPCM_FLO_MODEM_H */
