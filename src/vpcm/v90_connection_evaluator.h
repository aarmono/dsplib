/**
 * @file v90_connection_evaluator.h
 * @brief V90ConnectionEvaluator: the V.90 demodulator's connection-quality evaluator.
 *
 * The object receives the running average of the pre-decision SNR error (avePdsnr_, a weighted mean updated through updateAvePdsnr() by
 * V90Equalizer::process()) together with the demodulator phase, counts how long the quality stays beyond the thresholds of the parameter block, and
 * answers with a verdict code: 0 nothing, 1 one rate up, 2 one rate down, 3 rate down without restriction, 4 retrain, 5 fall back to V.34.
 * Definitions: v90_connection_evaluator.cpp.  The class is plain (no virtual functions) and 0xbc bytes long in the 32-bit layout checked by
 * v90_connection_evaluator_layout.inc (generated by tools/layout_gen.py).
 *
 * It reads many V90Parameters members and writes one of them: params_->rrnSilenceMinEchoEnergyForKeepRate (the echo-RRN state machine of
 * evaluateConnection()).
 */
#ifndef DSP_CLASSES_P17_H
#define DSP_CLASSES_P17_H

#include "core/dsp_cxx.h"
#include "pcm_parameters.h" /* V90Parameters */

class V90ConnectionEvaluator
{
public:
  explicit V90ConnectionEvaluator(V90Parameters* p); ///< binds the parameter block and calls reset()
  ~V90ConnectionEvaluator();
  void reset(); ///< back to the start-of-connection state, parameters re-read
  /** avePdsnr_ = the weighted mean of the old value (weight weight_) and x (weight w); weight_ += w */
  void updateAvePdsnr(float x, unsigned w);
  void updateCurrentConstellationData(short curDmin, float threshUp, float threshDown, float threshRetrain); ///< new constellation's thresholds
  void indicateRemoteRateReneg();                                                                            ///< count a far-end rate renegotiation
  unsigned evaluateConnection();                                                                             ///< verdict for the data phase: 0 .. 5
  unsigned evaluatePhase3();                                                                                 ///< verdict for phase 3 / TRN1d: 0, 4, 5
  unsigned evaluateMeanErrorStdPhase3(float std);            ///< phase-3 deviation check (no caller in the library): 0 or 5
  unsigned evaluateMeanErrorStdPhase4(float a, float b);     ///< not implemented: returns 0
  unsigned evaluatePhase4(float meanErrBefToAftUpdateRatio); ///< verdict for phase 4: 0, 4, 5
  unsigned indicateLocalRetrain();                           ///< count a local retrain: 4 or 5
  unsigned indicateRemoteRetrain();                          ///< count a remote retrain: 4 or 5
  void printStatus() const;                                  ///< print the counters (no caller in the library)

public:
  V90Parameters* params_;                    ///< parameter block, borrowed
  unsigned nofRetrainsSoFar_;                ///< retrains counted (faded by the fade counter)
  unsigned nofRateRenegSoFar_;               ///< far-end rate renegotiations counted
  unsigned nofRemoteRetrainsSoFar_;          ///< far-end retrains counted
  unsigned rateUpCounter_;                   ///< weights accumulated below threshUp_ (phase 3 / 4: above the V.34 fall-back threshold)
  unsigned rateDownCounter_;                 ///< weights accumulated above threshDown_
  unsigned retrainCounter_;                  ///< weights accumulated above threshRetrain_
  unsigned evaluatorCounter_;                ///< weights since the last rate change / retrain
  unsigned fadeCounter_;                     ///< weights since the start, drives the fade of the event counts
  int32_t debugCounter_;                     ///< weights since the last debug demand
  int32_t enableRrnDown_;                    ///< rate down allowed (parameter enableRrnDown)
  int32_t enableRrnUp_;                      ///< rate up allowed (parameter enableRrnUp)
  unsigned nofRemoteRateRenegBeforeRetrain_; ///< rate renegotiations after which a retrain is forced
  int32_t debugAlternate_;                   ///< debug demand: cycle rate up / retrain / rate down
  int32_t debugFallBack_;                    ///< debug demand: fall back to V.34
  int32_t debugRetrain_;                     ///< debug demand: retrain
  int32_t debugRateUp_;                      ///< debug demand: rate up
  int32_t debugRateDown_;                    ///< debug demand: rate down
  unsigned retrainCounterFadeCount_;         ///< weights per fade step of the retrain counts
  unsigned remoteRrnCounterFadeCount_;       ///< weights per fade step of the rate-renegotiation count
  unsigned rateUpDetectDuration_;            ///< weights threshUp_ must hold for a rate up
  unsigned minDurationInDataBeforeRrnUp_;    ///< minimum evaluatorCounter_ for a rate up
  unsigned rateDownDetectDuration_;          ///< weights threshDown_ must hold for a rate down
  unsigned minDurationInDataBeforeRrnDown_;  ///< minimum evaluatorCounter_ for a rate down
  unsigned retrainDetectDuration_;           ///< weights threshRetrain_ must hold for a retrain
  unsigned largeErrorDuration_;              ///< weights of large error before a phase-3 fall back (0x640)
  unsigned largeErrorDurationPhase4_;        ///< weights of large error before a phase-4 fall back (0x640)
  int32_t debugPeriod_;                      ///< weights between debug demands
  float avePdsnr_;                           ///< weighted running mean of the pre-decision SNR error
  unsigned weight_;                          ///< total weight behind avePdsnr_; 0 = nothing to evaluate
  int32_t delayedRetrainRequest_;            ///< a retrain was requested and is waiting for delayedRetrainEnable_
  int32_t delayedRetrainEnable_;             ///< the delayed retrain may fire
  int32_t altDebugState_;                    ///< position in the alternate debug sequence (0..3)
  int32_t phase3EvalActive_;                 ///< phase-3 evaluation selected
  int32_t trn1dEvalActive_;                  ///< TRN1d evaluation selected
  int32_t externalCommand_;                  ///< pending external demand, -1 = none (see evaluateConnection())
  int32_t rrnSilence_;                       ///< the rate renegotiation is to be done with silence
  int32_t retrainInsteadOfRateDown_;         ///< turn a rate-down verdict into a retrain
  int32_t noRestrictionRrn_;                 ///< the rate down is the no-restriction kind
  int16_t initDmin_;                         ///< minimum distance at the start of the evaluation, -1 = not latched
  int16_t curDmin_;                          ///< minimum distance of the current constellation
  float threshUp_;                           ///< error below which a rate up is considered
  float threshDown_;                         ///< error above which a rate down is considered
  float threshRetrain_;                      ///< error above which a retrain is considered
  float pdsnrV34DropThreshPhase4_;           ///< current phase-4 error level for a fall back to V.34
  int16_t phase4RatioCheckEnabled_;          ///< the one-shot phase-4 ratio check is still armed
  int16_t altRbsDetectedOnQc_;               ///< alternate RBS detected during quick connect (phase 3 retrains)
  int16_t echoRrnState_;                     ///< state of the echo-RRN machine, 0..3
  uint8_t unkb6_[2];                         ///< unused padding
  float echoRrnFactor_;                      ///< threshold factor the echo-RRN machine used last (1.52 or 1.39)
};

typedef V90ConnectionEvaluator P17_V90ConnectionEvaluator;

#include "v90_connection_evaluator_layout.inc"

#endif /* DSP_CLASSES_P17_H */
