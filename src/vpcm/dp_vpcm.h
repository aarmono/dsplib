/**
 * @file dp_vpcm.h
 * @brief Session state of the V.34 / V.90 / V.92 data pump and its operations record.
 *
 * Declares Z01_State, the per-session object that vpcm_create() allocates and every vpcm_* entry point of dp_vpcm.cpp works on, and Z01_DpOperations, the
 * record registered with the host for the three data pump ids.  The first five members mirror the host's `struct dp` (id, modem, status, op, dp_data);
 * the V.34 module object follows (V01_tagV34Object, v34/v34_object.h) and the sample / bit staging buffers of vpcm_run() come after it.  Everything
 * after the module object moves when that object's size changes, so the member order is checked against the 32-bit layout only (dp_vpcm_layout.inc,
 * generated by tools/layout_gen.py) and the 64-bit build derives its own offsets.
 *
 * Also declares the three VPCMXF_* functions that create, delete and terminate the VPcmFloModem (pcm_leaf_classes.h) the session object owns.
 */
#ifndef DSP_CLASSES_Z01_H
#define DSP_CLASSES_Z01_H

#include "v34/v34_object.h"
#include "core/dp_registry.h"

struct dsp_info; /* core/host_interface.h */

struct Z01_State
{
  int32_t id_;               ///< host `struct dp`: data pump id (DP_V34, DP_V90 or DP_V92); updated to the negotiated protocol when the link comes up
  void* modem_;              ///< host `struct dp`: the host modem, opaque
  uint8_t unk08_[4];         ///< host `struct dp`: status word, never touched here
  void* op_;                 ///< host `struct dp`: the operations record this session was created with
  Z01_State* dpData_;        ///< host `struct dp`: dp_data, points at the session object itself
  int32_t status_;           ///< last status returned by VPcmV34Progress()
  int32_t link_;             ///< link state: 0 = training, 1 = up, -1 = error
  int32_t bitsWanted_;       ///< number of bits the next modem_get_bits() call asks the host for
  int32_t trainCnt_;         ///< consecutive vpcm_run() calls that saw status 0; a training timeout is declared past 3000
  struct dsp_info* dspInfo_; ///< the host's connection summary (MDMPRM_DSPINFO): vpcm_delete() stores the connection type and the clock deviation in it
  V01_ModemParams* dp_;      ///< the data pump parameter block of the modem (dp_param_get())
  V01_tagV34Object v34_;     ///< the V.34 module object (its `ctx_` is the VPcmFloModem, `k56_` the K56flex handle)
  float inF_[160];           ///< receive samples converted to float for VPcmV34Progress()
  float outF_[160];          ///< transmit samples produced by VPcmV34Progress()
  uint32_t bitsIn_[1024];    ///< bits fetched from the host, one bit per word
  uint32_t bitsOut_[1024];   ///< bits produced by the protocol, one bit per word
  int32_t txCnt_;            ///< number of transmit samples queued in txBuf_
  uint16_t txBuf_[52];       ///< transmit samples produced but not yet delivered to the host
  int32_t pendCnt_;          ///< number of receive samples queued in pendBuf_
  uint16_t pendBuf_[52];     ///< receive samples left over because the protocol consumes multiples of four
  int32_t silence_;          ///< number of transmit samples still to be sent as silence before the protocol starts
  int32_t addDelay_;         ///< extra audio delay (samples) requested from the host while the protocol is past phase 2
};

typedef Z01_State Z01State;

/** The host's `struct dp_operations` (core/host_interface.h).  The function pointers are `void *` here because their prototypes need the host's types. */
struct Z01_DpOperations
{
  const char* name;
  int useCount;
  void* create;
  void* deleteFn;
  void* process;
  void* hangup;
};

extern "C"
{
  /* Create, delete and terminate the VPcmFloModem; defined in dp_vpcm.cpp */
  VPcmFloModem* VPCMXF_Create(int side, void* ctx, V01_ModemParams* params, unsigned rate, int mode);
  void VPCMXF_Delete(VPcmFloModem* m);
  int VPCMXF_SessionTermination(VPcmFloModem* m);
}

#pragma GCC diagnostic ignored "-Winvalid-offsetof"
#include "dp_vpcm_layout.inc"

#endif /* DSP_CLASSES_Z01_H */
