/**
 * @file v92_phase4_modulator.h
 * @brief Declaration of V92Phase4Modulator, the V.92 phase 4 (transmit) symbol generator.
 *
 * A plain class (no virtual functions): a state machine (state_, symbol counter cnt_, output marker event_) that produces one 16-bit symbol per
 * generateSymbol() call: patterns of +-level_ (Ru / RuNot, the differential bit stream inv_), the V92Mapper over mult_ scrambled bits per symbol
 * (TRN2u, E2u), the CP / SUV bit frames (generateSUVu() / generateCPu()) and the V92BitsToSymbol queue (FPE / FB1u / B1u data).  V92Modulator
 * embeds a pointer to it and calls generateSymbol() (via V92Modulator::progress()) and reset().  The owner (VPcmFloModem::runPcmModem()) reports
 * the events of the received signal through the exit* / recived* methods.
 *
 * The definitions are in v92_phase4_modulator_symbol.cpp (generateSymbol) and v92_phase4_modulator.cpp (everything else).  The object is 0x1cc
 * bytes in the i386 layout checked by v92_phase4_modulator_layout.inc (generated by tools/layout_gen.py from layouts/vpcm/v92_phase4_modulator_symbol.layout).
 *
 * States of generateSymbol():
 * - 0 Ru (CP bits in the differential stream); 1 Ru until the end of the frame -> 2 E1u (0xc symbols) -> 3 TRN2uModulation (until the owner's
 *   event); 4 TRN2uModulation to a multiple of 12 above 0x3137 -> 5 SUVu (the CP restarted at every frame; limit_ + 0x320 repeated-CP counts -> 0xd).
 * - 6 SUVu -> 0xc CPu; 8 SUVu -> 0xa FinalSUVu; 9 / 0xa / 0xb SUVu / CPu -> 0xf E2u; 0xc CPu terminated -> 5; 0xd repeated CPu.
 * - 0xf E2u (zeros) -> 0x17 (TRN2u second part at RRN) / 0x10 B1u (ones, 0x240 symbols -> 0x1c terminated, event 9) / 0x11 FB1u (FPE).
 * - 0x12 drain -> 0x13; 0x13 Ru pattern (0x180) -> 0x14 RuNot (0x18) -> 3; 0x17 / 0x18 TRN2u second part at RRN -> 5.
 * - 0x19 drain -> 0x1a Rm (0x180) -> 0x1b (FPE) -> 5; 0x1c data forever; 0x1d no output; 7, 0xe, 0x15, 0x16 and > 0x1d are illegal.
 */
#ifndef V92_PHASE4_MODULATOR_H
#define V92_PHASE4_MODULATOR_H

#include "core/dsp_cxx.h"
#include "dsp/dsp_int_templates.h" /* Scrambler<unsigned char, unsigned char> */
#include "pcm_leaf_classes.h"      /* V92Mapper */
#include "pcm_parameters.h"        /* V92Parameters */
#include "v92_cp.h"                /* V92CP, V92MappingParams */
#include "pcm_bits_to_symbol.h"    /* V92BitsToSymbol, V92Transmitter */
#include "v92_modulus_encoder.h"   /* V92ModulusEncoder (mode_) */

/** @brief States of V92Phase4Modulator::state_ (the enumerator names are descriptive; see the state table in the file header). */
enum V92Phase4ModulatorState
{
  V92P4_RU = 0,
  V92P4_RU_END = 1,
  V92P4_E1U = 2,
  V92P4_TRN2U = 3,
  V92P4_TRN2U_A = 4,
  V92P4_SUVU = 5,
  V92P4_SUVU_TO_CPU = 6,
  V92P4_STATE7 = 7,
  V92P4_FINAL_SUVU_ENTER = 8,
  V92P4_SUVU_9 = 9,
  V92P4_SUVU_10 = 10,
  V92P4_CPU_11 = 11,
  V92P4_CPU_END = 12,
  V92P4_REPEATED_CPU = 13,
  V92P4_STATE14 = 14,
  V92P4_E2U = 15,
  V92P4_B1U = 16,
  V92P4_FB1U = 17,
  V92P4_WAIT_RU = 18,
  V92P4_RU_PAT = 19,
  V92P4_RU_NOT = 20,
  V92P4_STATE21 = 21,
  V92P4_STATE22 = 22,
  V92P4_TRN2U_SECOND = 23,
  V92P4_TRN2U_SECOND_A = 24,
  V92P4_WAIT_RM = 25,
  V92P4_RM = 26,
  V92P4_FPE = 27,
  V92P4_TERMINATED = 28,
  V92P4_ERROR = 29
};

/**
 * @brief V.92 phase 4 symbol generator (state machine, one symbol per generateSymbol() call).
 *
 * Methods whose comment says "no caller" are not used by anything in the library (generateSymbol() carries the same logic inline).
 */
class V92Phase4Modulator
{
public:
  /**
   * @brief Build the scrambler (5, 0x17, 0x63), allocate the V92Mapper and store the collaborators.
   * @param p    V.92 parameter block (not owned)
   * @param b2s  bits-to-symbol queue shared with V92Modulator (not owned)
   * @param cp   CP frame builder (not owned); cp->cptSent_ is cleared
   * @param mp   data-phase mapping parameters (not owned, may be NULL)
   * @warning state_, cnt_, event_, the w* counters, level_, mult_, limit_, inv_, bits_ and cpBits_ are NOT initialised here; reset() must run first.
   *          cp is dereferenced without a NULL test and the V92Mapper allocation is not checked.
   */
  V92Phase4Modulator(V92Parameters* p, V92BitsToSymbol* b2s, V92CP* cp, V92MappingParams* mp);

  /** @brief Destroy and free the V92Mapper (when allocated); nothing is cleared. */
  ~V92Phase4Modulator();

  /** @brief Rate-renegotiation (RRN) start: clear the counters and flags and set w28_ (RRN in progress). */
  void resetBeforRRN();

  /** @brief Final phase-4 exchange (FPE) start: cnt_ = 0 and w3c_ = 1 (E2u / CPu / SUVu then run through the V92BitsToSymbol queue). */
  void resetBeforFPE();

  /** @brief Enter the repeated-CPu state and restart the CP frame.  No caller. */
  void enterRepeatedCP();

  /** @brief Ru pattern symbol: +level_ for (cnt_ - 1) % 6 <= 2, else -level_.  No caller. */
  short generateRu();

  /** @brief Inverted Ru pattern symbol.  No caller. */
  short generateRuNot();

  /** @brief Clear the flags of the second RRN section.  No caller. */
  void resetRRNSecondSection();

  /** @brief The CPt was received: leave Ru at a frame boundary (-> E1u) or switch to the run-to-end state 1. */
  void exitCPt();

  /** @brief The TRN2u was acknowledged: switch to the "run to a multiple of 12" state (4). */
  void exitTRN2u();

  /** @brief A SUV was received: finish the SUV frame and continue with CPu (or enter CPu at a boundary). */
  void recivedSUV();

  /** @brief First silent part of an RRN SUV: set the CP's flag_. */
  void recivedPartOneSilenceRrnSUV();

  /** @brief Second silent part of an RRN SUV: same as recivedSUV(). */
  void recivedPartTwoSilenceRrnSUV();

  /** @brief A CP was received: set w1c0_ and the CP's flag_, clear cptSent_. */
  void recivedCP();

  /** @brief A SUV was received after a tagged CP: move towards E2u at the next frame boundary. */
  void recivedSUVtag();

  /** @brief First silent part of a tagged RRN SUV: choose between E2u, SUVu->E2u and FinalSUVu by the frame position. */
  void recivedPartOneSilenceRrnSUVtag();

  /** @brief Second silent part of a tagged RRN SUV: same as recivedSUVtag(). */
  void recivedPartTwoSilenceRrnSUVtag();

  /** @brief A tagged CP was received: start the SUV / E2u sequence according to the frame position. */
  void recivedCPtag();

  /** @brief Ed was received: move to E2u at a frame boundary, else towards it. */
  void recivedEd();

  /** @brief The first Ed of an RRN was received: move to E2u (length 0xc) at a frame boundary. */
  void recivedFirstRrnEd();

  /**
   * @brief Rt received in the second TRN2u part of an RRN (only when w38_ != 0): enter SUVu at once if cnt_ > 0x95f and a multiple of 12,
   *        else switch to state 0x18.
   */
  void recivedRt();

  /**
   * @brief Hand mapping parameters to the bits-to-symbol queue and set its block size to 1.  No caller.
   * @param mp  mapping parameters; NULL only prints a debug line
   */
  void setMappingParams(V92MappingParams* mp);

  /** @brief Data symbol before the FPE.  No caller. @warning n and out are passed uninitialised to V92BitsToSymbol::process(), which writes both. */
  short generateDataSymbolBeforeFPE();

  /** @brief Data symbol before the RRN.  No caller. @warning n and out are passed uninitialised to V92BitsToSymbol::process(), which writes both. */
  short generateDataSymbolBeforeRRN();

  /** @brief Rm symbol (scrambled ones through the queue).  No caller. */
  short generateRm();

  /** @brief B1u symbol (scrambled ones through the queue).  No caller. */
  short generateB1u();

  /** @brief TRN2u symbol (scrambled ones through the mapper).  No caller. */
  short generateTRN2u();

  /** @brief E2u symbol (scrambled zeros through the mapper, or through the queue when w3c_ is set).  No caller. */
  short generateE2u();

  /** @brief CPu symbol: the CP bit stream through the scrambler and mapper (or the queue when w3c_ is set).  Called by generateSymbol(). */
  short generateCPu();

  /** @brief SUVu symbol: same code as generateCPu(); called by generateSymbol(). */
  short generateSUVu();

  /** @brief E1u symbol (scrambled zeros in the differential stream).  No caller. */
  short generateE1u();

  /** @brief CPt symbol (CP bits after the first 0x18 symbols).  No caller. */
  short generateCPt();

  /**
   * @brief Restart the generator in state `st` and optionally run n symbols.
   * @param level  symbol magnitude
   * @param b      mapper parameter (mult_ = b + 2 bits per mapped block)
   * @param st     initial state
   * @param n      number of symbols to generate and discard
   * @param limit  repeat limit stored in limit_ (V92Phase2Info::rtd_)
   * @note  Does not clear w08_, w24_, w38_ and w1b8_.
   */
  void reset(short level, unsigned char b, V92Phase4ModulatorState st, unsigned n, unsigned limit);

  /**
   * @brief Produce the next symbol of the current state and advance the state machine.
   * @return the 16-bit symbol (0 for the terminal states)
   * @note  cnt_ is incremented and event_ cleared BEFORE the state dispatch; event_ = 9 marks the end of phase 4.
   * @warning cp_ is dereferenced without a NULL test in most states; a zero cpLen_, cpFrame_ or mult_ is a division by zero.
   */
  short generateSymbol();

public:
  unsigned state_;         ///< V92Phase4ModulatorState
  unsigned cnt_;           ///< symbols produced in the current state
  unsigned w08_;           ///< read position in cpBits_ (advanced modulo cpLen_ per scrambled CP bit); cleared when a SUV starts
  unsigned event_;         ///< event for the owner, set by generateSymbol(); 9 = phase 4 finished
  unsigned char pad10_[8]; ///< never touched
  unsigned cpCnt_;         ///< SUV frames counted since CPu ended; above limit_ + 0x320 the repeated-CPu state is entered
  unsigned char cpFlag_;   ///< non-zero while cpCnt_ counts
  unsigned char pad1d_[3]; ///< never touched
  unsigned w20_;           ///< non-zero once a tag / Ed event has already steered the state machine toward E2u
  unsigned w24_;           ///< minimum symbol count of the second TRN2u part of an RRN (0x1f44 or 0xfa0)
  unsigned w28_;           ///< RRN in progress (set by resetBeforRRN(), cleared by reset())
  unsigned rrnSilence_;    ///< evaluator silence word, copied here by the owner at RRN start; SUVu tails pass it to V92CP::setSUV() [medium confidence]
  unsigned w30_;           ///< set by the owner on the first silent part of an RRN SUV; selects the second TRN2u part after E2u
  unsigned w34_;           ///< second TRN2u part of the RRN already done
  unsigned w38_;           ///< copy of the received CP's short-frame word (V90CP::wCa0_); non-zero selects the shorter second TRN2u part (0xfa0) and Rt exit
  unsigned w3c_;           ///< FPE mode: E2u / CPu / SUVu go through the V92BitsToSymbol queue instead of the direct mapper
  unsigned short level_;   ///< symbol magnitude
  unsigned char b42_;      ///< mapper parameter b passed to reset()
  unsigned char mult_;     ///< bits per mapped block (b + 2)
  unsigned limit_;         ///< repeat limit (V92Phase2Info::rtd_)
  V92MappingParams* mp_;   ///< data-phase mapping parameters (not owned)
  Scrambler<unsigned char, unsigned char> scr_; ///< scrambler of the transmitted bits
  V92BitsToSymbol* b2s_;                        ///< bits-to-symbol queue (not owned)
  V92Mapper* mapper_;                           ///< block mapper (heap, owned)
  V92CP* cp_;                                   ///< CP frame builder (not owned)
  unsigned inv_;                                ///< differential stream state (32-bit; XORed with the scrambler output)
  unsigned char bits_[300];                     ///< scrambled bits of the current block
  unsigned char* cpBits_;                       ///< current CP / SUV bit vector (owned by cp_)
  unsigned cpLen_;                              ///< length of cpBits_
  unsigned cpFrame_;                            ///< symbols per CP frame (cpLen_ / multiplier)
  unsigned char pad1b4_[4];                     ///< never touched
  unsigned w1b8_;                               ///< length of E1u / E2u in symbols (0xc, or 0xd when extendEu_ is set)
  unsigned extendEu_;                           ///< set by runPcmModem when the received CP has extendEu_ != 0; selects the E2u length 0xd [medium confidence]
  unsigned w1c0_;                               ///< a CP has been received (set by recivedCP() / recivedCPtag())
  unsigned w1c4_;                               ///< the SUVu -> CPu switch has been done (set by that switch, cleared at RRN start)
  V92Parameters* params_;                       ///< V.92 parameter block (not owned)
};

typedef V92Phase4Modulator P32_V92Phase4Modulator;

#pragma GCC diagnostic ignored "-Winvalid-offsetof"
#include "v92_phase4_modulator_layout.inc"

#endif /* V92_PHASE4_MODULATOR_H */
