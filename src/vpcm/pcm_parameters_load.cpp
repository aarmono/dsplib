/**
 * @file pcm_parameters_load.cpp
 * @brief V90Parameters::loadParams(): read the V.90 parameter file key by key.
 *
 * The function is a straight line of 295 calls Vparser_read_int() / Vparser_read_float() (parser, "KEY", &member) (139 int, 156 float; 291 distinct
 * members) and nothing else: no store, no branch.  The reader functions are stubs that read nothing (pcm_leaf_classes.cpp), so the behaviour of this
 * function is the order and the arguments of those calls; a test harness can interpose the two readers and compares the whole call sequence
 * (reader, parser argument, key text, destination member) and the object after the call.
 *
 * The body is generated by tools/params_gen.py between the BEGIN / END GENERATED markers.  The member names are the key strings in camelCase (see
 * pcm_parameters.h).  Facts that the sequence reproduces exactly:
 *   - BLL_TRN1_QC_SLOW_K2 is read into bllTrn1QcSlowK1 (offset 0xf0 of the 32-bit layout), so bllTrn1QcSlowK2 (0xf4) is never loaded;
 *   - the three GERMAN_PBX_LINEAR_EQU_DIL_* keys are read into the members of the non-German LINEAR_EQU_DIL_* keys, so the germanPbxLinearEquDil*
 *     members are never loaded;
 *   - the order of the calls is the order of the parameter file definition, not the member order.
 */

