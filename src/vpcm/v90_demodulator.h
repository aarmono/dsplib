/**
 * Values of V90Demodulator::phase_.  The names follow the debug prints of the entry methods ("enter Phase 3", "enter Phase 4", "enter Data Phase",
 * "enter Data steady state", "Enter Channel Verification").  0 is the value reset() stores; progress() treats every value above 4 like the data phases.
 */
enum V90DemodPhase
{
  V90D_PHASE_IDLE = 0,
  V90D_PHASE_3 = 1,
  V90D_PHASE_4 = 2,
  V90D_PHASE_DATA = 3,
  V90D_PHASE_DATA_STEADY = 4,
  V90D_PHASE_CHANNEL_VERIFICATION = 5
};

class V90Demodulator
{
public:
  /**
   * @brief Build the demodulator and the receiver chain it owns.
   * @param n        maximum block length passed to progress(); sizes the sample buffers and the demapper
   * @param info     phase 2 information (round-trip delay, probing results), owned by V90Modem
   * @param jd       V.90 Jd object (session 0)
   * @param jd92     V.92 Jd object (session != 0)
   * @param dil      digital impairment learning descriptor
   * @param mp1      mapping parameters designed by the TRN2d designer (uplink)
   * @param mp2      mapping parameters of the data constellation
   * @param cpInfo   additional CP information handed to the transmit side (TRN1d RMS, flags)
   * @param cp       V.90 CP structure
   * @param mp       V.90 MP structure
   * @param codec    hardware codec type of the host
   * @param params   parameter block (V90Parameters)
   * @param mode     computational mode handed to the equalizer
   * @param session  0 for V.90, non-zero for V.92
   * @warning The sysdep_malloc() results are not checked for NULL.
   */
  V90Demodulator(unsigned n, V90Phase2Info* info, V90Jd* jd, V92Jd* jd92, tagV90DILdescriptor* dil, V90MappingParams* mp1, V90MappingParams* mp2,
                 tagV90AdditionalCPinfo* cpInfo, V90CP* cp, V90MP* mp, __tHardwareCodecTypes__ codec, V90Parameters* params, V90ComputationalMode mode,
                 unsigned session);
  /** @brief Report the timing statistics (see sessionTermination()), destroy the receiver chain and free the buffers. */
  ~V90Demodulator();
  /** @brief End-of-session hook: print and possibly store the timing-offset statistics and clear the phase 3 verification status.  @return always 0 */
  int sessionTermination();
  /** @brief Enter phase 4 (if not already there) with the standard timeout.  Not called from within the library. */
  void enterPhase4();
  /** @brief Enter steady-state data: store the timing-offset statistics (when evaluation is enabled) and stop the linear-mapping study. */
  void enterDataSteadyState();
  /** @brief Rate-renegotiation (RRN) request detected in data: re-enter phase 4 with the shorter RRN timeout and arm the silence-RRN information. */
  void enterRRN();
  /** @brief FPE detected: re-enter phase 4 with the RRN timeout.  Not called from within the library. */
  void enterFPE();
  /** @brief Set the session flag (0 V.90, else V.92) here and in the phase 3 and phase 4 demodulators. */
  void setSessionFlag(unsigned f);
  /** @brief Enter phase 3: reset the phase 3 demodulator, the equalizer, the verifier and the connection evaluator; select the pre-filter. */
  void enterPhase3();
  /** @brief Current bit rate in bit/s (0 until a constellation has been designed). */
  int getBitRate() const;
  /** @brief Copy the six suspected RBS phases to `out[0..5]`.  Not called from within the library. */
  void getRbsPattern(unsigned* out) const;
  /** @brief Tell the connection evaluator that the remote side requested a rate renegotiation and mark the constellation designer. */
  void indicateRemoteRateReneg() const;
  /** @brief Fill the diagnostics record (counters, bit rate, mean error and power in dB, RTD, RBS pattern) and print it.  Not called within the library. */
  void getAT_UD(TAG_DiagnosticResults* r) const;
  /** @brief Leave phase 3: publish the TRN1d RMS, design the TRN2d constellation, enter phase 4 if phase 3 terminated, reset the phase 4 demodulator. */
  void exitPhase3();
  /** @brief Enter the first data phase (rate known): set the data print periods, steady BLL state, restart the linear-mapping study. */
  void enterDataPhase();
  /** @brief Reset the connection evaluator and the phase 3 verification status. */
  void reInit();
  /** @brief Reset the whole receive chain to idle.  @param arg quick-connect flag (stored in `retrainOk_` and the equalizer). */
  void reset(unsigned arg);
  /** @brief Enter channel verification (quick-connect line verification): reset(1) and restart the phase 3 demodulator waiting for QTS.  `a` is unused. */
  void enterChannelVerification(short a, short b);
  /** @brief Process one block of received samples; see v90_demodulator_progress.cpp. */
  void progress(int* out, unsigned& outCnt, float* in, unsigned n);

public:
  __tHardwareCodecTypes__ hwCodec_;     ///< hardware codec type of the host
  V90Phase2Info* info_;                 ///< phase 2 information (borrowed)
  V90Jd* jd_;                           ///< V.90 Jd object (borrowed)
  V92Jd* jd92_;                         ///< V.92 Jd object (borrowed)
  tagV90DILdescriptor* dil_;            ///< digital impairment learning descriptor (borrowed)
  V90MappingParams* mp1_;               ///< mapping parameters of the TRN2d design (borrowed)
  V90MappingParams* mp2_;               ///< mapping parameters of the data constellation (borrowed)
  V90TRN2Designer* trn2d_;              ///< TRN2d designer (owned)
  tagV90AdditionalCPinfo* cpInfo_;      ///< additional CP information for the transmit side (borrowed)
  V90CP* cp_;                           ///< V.90 CP structure (borrowed)
  V90MP* mp_;                           ///< V.90 MP structure (borrowed)
  V90Parameters* params_;               ///< parameter block (borrowed)
  unsigned session_;                    ///< 0 for V.90, non-zero for V.92
  unsigned phase_;                      ///< receive phase, V90DemodPhase
  unsigned symCnt_;                     ///< samples counted in the current phase
  unsigned state_;                      ///< outcome / event code of the last progress() call (V90DemodState)
  unsigned flag40_;                     ///< remote-retrain energy detector armed (set once the Agc has settled or timing is running)
  unsigned timeCnt_;                    ///< samples counted toward the phase 4 timeout
  unsigned timeLimit_;                  ///< phase 4 timeout, in samples
  Agc<float> agc_;                      ///< automatic gain control (embedded)
  V90PreFilter pf_;                     ///< input pre-filter (embedded)
  V90Resampler rs_;                     ///< resampler with the BLL timing loop (embedded)
  V90ConstellationPower cpow_;          ///< constellation power computation (embedded)
  V90Equalizer* eq_;                    ///< equalizer (owned)
  V90Phase3Demodulator* p3_;            ///< phase 3 demodulator (owned)
  V90Phase4Demodulator* p4_;            ///< phase 4 demodulator (owned)
  V90Demapper* dem_;                    ///< demapper (owned)
  Descrambler<unsigned char, int> scr_; ///< descrambler (embedded)
  V90ConstellationDesigner* cdes_;      ///< constellation designer (owned)
  V90ConnectionEvaluator* ce_;          ///< connection evaluator (owned)
  V90SpectralVerifier sv_;              ///< spectral verifier (embedded)
  V90AutoDigitalImpDetector* adid_;     ///< automatic digital impairment detector (owned)
  float dilScale_;             ///< pad gain found by the DIL study; reported as the TRN1d RMS by exitPhase3() (not initialised by the constructor or reset())
  float* inBuf_;               ///< pre-filtered input block, `n` floats
  float* rsBuf_;               ///< resampler output, 3 * `n` floats
  unsigned rsCnt_;             ///< number of valid samples in `rsBuf_`
  short* decBuf_;              ///< equalizer decisions, `n` * 2 shorts
  float* eqBuf_;               ///< equalizer output, 2 * `n` floats
  unsigned eqCnt_;             ///< number of valid entries in `eqBuf_`
  unsigned char* byteBuf_;     ///< demapper output bytes, 8 * `n`
  unsigned framePos_;          ///< symbol position within the 6-symbol frame
  unsigned cnt23_;             ///< number of blocks that ended with outcome 0x23 (rate renegotiation detected)
  unsigned cnt1f_;             ///< number of blocks that ended with outcome 0x1f .. 0x21 (drop to V.34 / V.90 fall-back / retrain)
  unsigned cnt26_;             ///< number of blocks that ended with outcome 0x26 (energy drop)
  unsigned flag270_;           ///< set when a silence-RRN or Ed event was seen in phase 4; cleared by reset()
  float designErr_;            ///< mean error remembered when Ed arrived on a silence RRN (noise estimate for the redesign)
  unsigned timingHistoryEval_; ///< copy of timingHistoryEvaluationEnabled taken in enterDataSteadyState(); cleared by reset()
  unsigned quietCnt_;          ///< consecutive samples with the Agc power below the energy-drop threshold
  unsigned char designed_;     ///< non-zero once a data constellation has been designed
  unsigned char pad281_[3];    ///< padding (never accessed)
  unsigned errPrintCnt_;       ///< samples since the last error-energy print
  unsigned errPrintPeriod_;    ///< error-energy print period, in samples (per phase)
  unsigned tmPrintCnt_;        ///< samples since the last timing-offset print
  unsigned tmPrintPeriod_;     ///< timing-offset print period, in samples (per phase)
  unsigned retrainOk_;         ///< quick-connect flag given to reset(); non-zero selects the retrain (quick-connect) timing-loop schedule and outcomes
};

typedef V90Demodulator P43_V90Demodulator; /* alias used by the checks in v90_demodulator_layout.inc */

