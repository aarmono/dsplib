/**
 * @file v90_demodulator.h
 * @brief V90Demodulator: the receive side (analog-modem end) of the V.90 / V.92 PCM modem.
 *
 * V90Modem embeds one V90Demodulator and calls progress() once per block of samples (v90_demodulator_progress.cpp); the constructor, destructor, the
 * phase entry / exit methods, reset() and the small accessors are in v90_demodulator.cpp.  The class has no virtual functions and no base class.
 *
 * It EMBEDS six objects: an Agc<float> (`agc_`), a V90PreFilter (`pf_`, a FloatFIR), a V90Resampler (`rs_`, timing recovery with the BLL timing loop),
 * a V90ConstellationPower (`cpow_`), a Descrambler<unsigned char, int> (`scr_`) and a V90SpectralVerifier (`sv_`).  It OWNS (sysdep_malloc, placement new,
 * freed in the destructor) the receiver chain: the V90Equalizer (`eq_`), V90Phase3Demodulator (`p3_`), V90Phase4Demodulator (`p4_`), V90Demapper (`dem_`),
 * V90ConstellationDesigner (`cdes_`), V90ConnectionEvaluator (`ce_`), V90AutoDigitalImpDetector (`adid_`), V90TRN2Designer (`trn2d_`) and five sample
 * buffers.  The parameter, phase-2 info, Jd, DIL, mapping-parameter, MP and CP objects are owned by V90Modem and only referenced here.
 *
 * Signal path of progress(): V90PreFilter -> Agc -> V90Resampler -> V90Equalizer::process() (which leaves the phase event in `eq_->event_`) -> a state
 * machine on `phase_` (0 idle, 1 phase 3: spectral verifier plus the Sd / TRN1d / DIL handlers, 2 phase 4: timeout plus the constellation design from the
 * mean error, 3 first data call, 4 steady-state data: V90Demapper and Descrambler).  The handlers set `state_`, the outcome code returned to the caller
 * (0x1f fall back to V.34, 0x21 retrain, 0x22 .. 0x26; codes in v90_demod_state.h), and drive the resampler's timing loop (setBllState).
 *
 * The 32-bit member layout is asserted in v90_demodulator_layout.inc (generated by tools/layout_gen.py).
 */
