/**
 * @file pcm_dil.cpp
 * @brief V.90 / V.92 DIL (digital impairment learning) descriptor: the descriptor tables, the segment helpers and the two frame packers.
 *
 * Six functions and eight constant tables (TO, H, N, REF, TP, SP, Ltp, Lsp; index 0 = option ADI, 1 = option ADI_QC):
 * - setDilDescriptor() copies one option's tables into a tagV90DILdescriptor (pcm_dil.h).
 * - getSegmentPointer() maps a TO value to one of the eight segments of a PCM type; calculateDilLength() (two overloads: from a DilType, which
 *   no caller uses, and from a filled descriptor) sums 6 + 6 * H[segment] over the N entries of TO.
 * - DILdescriptorPacker() builds the V.90 frame (one `short` per bit) and V92DILdescriptorPacker() the V.92 frame (one byte per bit, with debug prints).
 *
 * Frame layout (both packers): 17 ones, then every index that is a multiple of 17 is a 0 start bit (the same grid as the CP frames); header bytes
 * N, Lsp - 1 and Ltp - 1; two data zones (the SP and TP symbols, 16 per grid row, zero-padded to a multiple of 17 slots: n = 17 * ceil(L / 16)); the 16
 * bytes H / REF as eight rows of two 7-bit bytes; the TO bytes as ceil(N / 2) rows of two 7-bit bytes; a CRC of 16 parity registers (taps 3 and 10)
 * over everything after the 18th slot; and the final length (padded to even).  The V.92 packer adds a block of 16 ones + zeros ("V.92 info")
 * before the CRC.  The row counts ceil(L / 16) and ceil(N / 2) are computed in integers; for byte-valued counts they equal the floating-point
 * ceilings a reference computation would use (checked by sweeping every byte value).
 *
 * Hazards:
 * - The length byte minus one is formed as an int, so a length of 0 sends seven one-bits.
 * - The TO rows read to_[2j + 1] also for an odd N, i.e. one byte past the last entry.
 * - calculateDilLength() reads H[seg] with seg == 8 (= REF[0], since `hr_` holds H then REF) when a value exceeds every segment limit.
 * - A DilType >= 2 is rejected only by the DilType overload of calculateDilLength(); a PcmType >= 2 indexes past the segment-limit table.
 * - The debug prints of the V.92 packer pass pointers as `%X` words (the low 32 bits on a 64-bit host), and the "temp calculation" value is z1 + 33
 *   (an index, not a pointer).
 *
 * Real C++, no exceptions, no RTTI, freestanding headers only, C++98.  Declarations and the descriptor struct: pcm_dil.h.
 */

