static const unsigned char Ltp[2] = {0x78, 0x3c};

static const unsigned char Lsp[2] = {0x78, 0x3c};

/* segment limits of getSegmentPointer(), one row of eight per PcmType */
static const int kSegLimit[2][8] = {{15, 31, 47, 63, 79, 95, 111, 127}, {31, 47, 63, 79, 95, 111, 127, 0}};

/* ---- helpers (static inline) ---- */

/* ceil(v / 16) and ceil(v / 2) for a byte-valued count: the number of 16-symbol groups and of 2-byte pairs */
static inline int ceilDiv16(unsigned v) { return (int)((v + 15u) >> 4); }
static inline int ceilDiv2(unsigned v) { return (int)((v + 1u) >> 1); }

/* Store the low seven bits of v, least significant first, one `short` per bit (arithmetic shifts of an int: a negative v sends ones);
 * bits7b() is the byte form. */
static inline void bits7(short* o, int v)
{
  for (int k = 0; k < 7; k++)
  {
    o[k] = (short)(v & 1);
    v >>= 1;
  }
}
static inline void bits7b(unsigned char* o, int v)
{
  for (int k = 0; k < 7; k++)
  {
    o[k] = (unsigned char)(v & 1);
    v >>= 1;
  }
}

/* One 17-slot row of two 7-bit bytes: [7 bits][0][7 bits][0][0]; rowPairB() is the byte-per-bit form. */
static inline void rowPair(short* o, int a, int b)
{
  bits7(o, a);
  o[7] = 0;
  bits7(o + 8, b);
  o[15] = 0;
  o[16] = 0;
}
static inline void rowPairB(unsigned char* o, int a, int b)
{
  bits7b(o, a);
  o[7] = 0;
  bits7b(o + 8, b);
  o[15] = 0;
  o[16] = 0;
}

/* One step of the 16-register parity CRC: s = bit + r0; every register takes its successor, except r3' = (r4 + s) & 1, r10' = (r11 + s) & 1, r15' = s & 1. */
static inline void crcStep(int* r, int bit)
{
  int s = bit + r[0];
  int t3 = (r[4] + s) & 1;
  int t10 = (r[11] + s) & 1;
  for (int k = 0; k < 15; k++)
    r[k] = r[k + 1];
  r[3] = t3;
  r[10] = t10;
  r[15] = s & 1;
}

/* Feed the rows of 16 bits (indices 18 + 17 t .. 33 + 17 t, t = 0 .. (z - 18) / 17) in front of the grid slot z into the CRC; crcRowsB() is the byte form. */
static inline void crcRows(int* r, const short* out, int z)
{
  int rows = (z - 18) / 17 + 1;
  for (int t = 0; t < rows; t++)
    for (int i = 18 + 17 * t; i < 34 + 17 * t; i++)
      crcStep(r, (int)out[i]);
}
static inline void crcRowsB(int* r, const unsigned char* out, int z)
{
  int rows = (z - 18) / 17 + 1;
  for (int t = 0; t < rows; t++)
    for (int i = 18 + 17 * t; i < 34 + 17 * t; i++)
      crcStep(r, (int)out[i]);
}

/**
 * @brief Fill a descriptor with the tables of one DIL option.
 * @param d  descriptor to fill (N, Lsp, Ltp, SP, TP, TO and H / REF are written)
 * @param t  DIL_ADI or DIL_ADI_QC (only these two print a debug message)
 * @warning Other values of `t` index past the two-entry tables.
 */
void setDilDescriptor(tagV90DILdescriptor* d, DilType t)
{
  d->N_ = N[t];
  d->Lsp_ = Lsp[t];
  d->Ltp_ = Ltp[t];
  for (unsigned i = 0; i < Lsp[t]; i++)
    d->sp_[i] = SP[t][i];
  for (unsigned i = 0; i < Ltp[t]; i++)
    d->tp_[i] = TP[t][i];
  for (unsigned i = 0; i < N[t]; i++)
    d->to_[i] = TO[t][i];
  for (unsigned i = 0; i < 8; i++)
    d->hr_[i] = H[t][i];
  for (unsigned i = 0; i < 8; i++)
    d->hr_[8 + i] = REF[t][i];
  if (t == 0)
    edprintf("V90DilDescriptorSettings: DIL descriptor set to option ADI.\r\n");
  else if (t == 1)
    edprintf("V90DilDescriptorSettings: DIL descriptor set to option ADI_QC.\r\n");
}

/**
 * @brief Find the segment of a TO value.
 * @param p  PCM type (0 or 1; selects the row of the segment-limit table)
 * @param v  value to classify (signed comparison)
 * @return the first segment index whose limit is >= v, at most (p != 1) + 7 (8 when v exceeds every limit of PcmType 0)
 */
int getSegmentPointer(PcmType p, int v)
{
  const int* limit = &kSegLimit[0][0];
  unsigned end = (p != 1) + 7;
  unsigned i = 0;
  while (i < end && limit[p * 8 + (int)i] < v)
    i++;
  return (int)i;
}

/**
 * @brief DIL length in bits from the built-in tables of an option.
 * @param t  DIL option; a value above 1 gives 0
 * @param p  PCM type
 * @return the sum over the N entries of TO of 6 + 6 * H[segment]
 * @note  No caller uses this overload; the descriptor overload is the live one.
 */
int calculateDilLength(DilType t, PcmType p)
{
  int len = 0;
  if (t > 1)
    return 0;
  for (unsigned j = 0; j < N[t]; j++)
  {
    int seg = getSegmentPointer(p, TO[t][j]);
    len += 6 + 6 * (int)(H[t][seg]);
  }
  return len;
}

/**
 * @brief DIL length in bits of a filled descriptor.
 * @param d  descriptor, or NULL
 * @param p  PCM type
 * @return the sum over the N entries of d->to_ of 6 + 6 * hr_[segment]; 0 for a NULL descriptor
 * @warning A TO value above every segment limit of PcmType 0 selects segment 8, which reads hr_[8] (= REF[0]) rather than an H entry.
 */
int calculateDilLength(tagV90DILdescriptor* d, PcmType p)
{
  int len = 0;
  if (d == 0)
    return 0;
  for (unsigned j = 0; (unsigned)d->N_ > j; j++)
  {
    int seg = getSegmentPointer(p, d->to_[j]);
    len += 6 + 6 * (int)d->hr_[seg];
  }
  return len;
}

/**
 * @brief Pack a descriptor into the V.90 DIL frame, one `short` (0 / 1) per bit.
 * @param d    descriptor to send
 * @param out  frame buffer, large enough for the frame (about 0x34 + 17 * (ceil(Lsp / 16) + ceil(Ltp / 16) + 8 + ceil(N / 2)) + 0x44 entries)
 * @param len  receives the frame length in bits, padded to even
 * @note  See the file header for the frame layout.  The CRC covers everything after the 18th slot.
 */
extern "C" void DILdescriptorPacker(tagV90DILdescriptor* d, short* out, short* len)
{
  int i;

  /* header: 17 ones, the start bit, N (8 bits), nine zeros, Lsp - 1 and Ltp - 1 (7 bits each, a zero after each) */
  for (i = 0; i <= 0x10; i++)
    out[i] = 1;
  out[0x11] = 0;
  {
    int v = d->N_;
    for (i = 0x12; i <= 0x19; i++)
    {
      out[i] = (short)(v & 1);
      v >>= 1;
    }
  }
  for (i = 0x1a; i <= 0x22; i++)
    out[i] = 0;
  bits7(out + 0x23, (int)d->Lsp_ - 1);
  out[0x2a] = 0;
  bits7(out + 0x2b, (int)d->Ltp_ - 1);
  out[0x32] = 0;
  out[0x33] = 0;

  /* zone 1: the SP symbols (a 0 start bit in front of every symbol that would land on a grid index), zero padded to n1 slots */
  const int n1 = 17 * ceilDiv16(d->Lsp_);
  int c = 0;
  for (i = 0; (int)d->Lsp_ > i; i++)
  {
    if ((c + 0x34) % 17 == 0)
      out[0x34 + c++] = 0;
    out[0x34 + c++] = (short)d->sp_[i];
  }
  while (c < n1)
    out[0x34 + c++] = 0;

  /* zone 2: the TP symbols */
  const int n2 = 17 * ceilDiv16(d->Ltp_);
  c = 0;
  for (i = 0; (int)d->Ltp_ > i; i++)
  {
    if ((n1 + c + 0x34) % 17 == 0)
      out[0x34 + n1 + c++] = 0;
    out[0x34 + n1 + c++] = (short)d->tp_[i];
  }
  for (int e = 0x34 + n1 + c; e < 0x34 + n1 + n2; e++)
    out[e] = 0;

  /* H / REF: eight rows of two bytes */
  const int s = n1 + n2;
  for (int r = 0; r < 8; r++)
    rowPair(out + s + 0x34 + 17 * r, d->hr_[2 * r], d->hr_[2 * r + 1]);

  /* TO: ceil(N / 2) rows of two bytes (the bound is re-read from the descriptor every iteration) */
  int k = 0;
  for (int j = 0; ceilDiv2(d->N_) > j; j++)
  {
    rowPair(out + s + 0xbc + 17 * j, d->to_[2 * j], d->to_[2 * j + 1]);
    k = j + 1;
  }
  const int z = s + 17 * k + 0xbb; /* a grid index: the last slot of the last row */
  out[z] = 0;

  /* CRC: sixteen registers preset to one, fed with every bit after the 18th slot, then sent in register order */
  int r[16];
  for (i = 0; i < 16; i++)
    r[i] = 1;
  crcRows(r, out, z);
  for (i = 0; i < 16; i++)
    out[z + 1 + i] = (short)r[i];
  out[z + 17] = 0;
  if (z & 1)
  {
    *len = (short)(z + 19);
    out[z + 18] = 0;
  }
  else
  {
    *len = (short)(z + 18);
  }
}

/**
 * @brief Pack a descriptor into the V.92 DIL frame, one byte (0 / 1) per bit.
 * @param d    descriptor to send
 * @param out  frame buffer (the V.90 layout plus the 0x22-slot "V.92 info" block)
 * @param len  receives the frame length in bits, padded to even
 * @note  Same layout as DILdescriptorPacker() with the V.92 info block (sixteen ones, then zeros) in front of the CRC.  Prints debug lines at
 *        debug level above 1.
 */
void V92DILdescriptorPacker(tagV90DILdescriptor* d, unsigned char* out, int* len)
{
  unsigned char pre[19]; /* the V.92 info preset vector: sixteen ones, then three zeros */
  int i;
  for (i = 0; i < 16; i++)
    pre[i] = 1;
  pre[16] = 0;
  pre[17] = 0;
  pre[18] = 0;

  /* entry debug prints: each is guarded by its own re-read of the debug level; the first failed guard ends the chain */
  do
  {
    if (dsplibs_debug_level > 1)
      dsplibs_debug_printf("## Debug: pParamObj address = %X\r\n", (unsigned)(uintptr_t)d);
    else
      break;
    if (dsplibs_debug_level > 1)
      dsplibs_debug_printf("## Debug: BitVector address = %X\r\n", (unsigned)(uintptr_t)out);
    else
      break;
    if (dsplibs_debug_level > 1)
      dsplibs_debug_printf("## Debug: Cnt address = %X\r\n", (unsigned)(uintptr_t)len);
    else
      break;
    if (dsplibs_debug_level > 1)
      dsplibs_debug_printf("## Debug: pParamObj->N = %d\r\n", (unsigned)d->N_);
    else
      break;
    if (dsplibs_debug_level > 1)
      dsplibs_debug_printf("## Debug: pParamObj->Lsp = %d\r\n", (unsigned)d->Lsp_);
    else
      break;
    if (dsplibs_debug_level > 1)
      dsplibs_debug_printf("## Debug: pParamObj->Ltp = %d\r\n", (unsigned)d->Ltp_);
  } while (0);

  /* header, as in the V.90 packer */
  for (i = 0; i <= 0x10; i++)
    out[i] = 1;
  out[0x11] = 0;
  {
    int v = d->N_;
    for (i = 0x12; i <= 0x19; i++)
    {
      out[i] = (unsigned char)(v & 1);
      v >>= 1;
    }
  }
  for (i = 0x1a; i <= 0x22; i++)
    out[i] = 0;
  bits7b(out + 0x23, (int)d->Lsp_ - 1);
  out[0x2a] = 0;
  bits7b(out + 0x2b, (int)d->Ltp_ - 1);
  out[0x32] = 0;
  out[0x33] = 0;

  /* zones 1 and 2: the SP and TP symbols with grid start bits, zero padded */
  const int n1 = 17 * ceilDiv16(d->Lsp_);
  int c = 0;
  for (i = 0; (int)d->Lsp_ > i; i++)
  {
    if ((c + 0x34) % 17 == 0)
      out[0x34 + c++] = 0;
    out[0x34 + c++] = d->sp_[i];
  }
  while (c < n1)
    out[0x34 + c++] = 0;

  const int n2 = 17 * ceilDiv16(d->Ltp_);
  c = 0;
  for (i = 0; (int)d->Ltp_ > i; i++)
  {
    if ((n1 + c + 0x34) % 17 == 0)
      out[0x34 + n1 + c++] = 0;
    out[0x34 + n1 + c++] = d->tp_[i];
  }
  for (int e = 0x34 + n1 + c; e < 0x34 + n1 + n2; e++)
    out[e] = 0;

  /* H / REF rows, then the TO rows */
  const int s = n1 + n2;
  for (int r = 0; r < 8; r++)
    rowPairB(out + s + 0x34 + 17 * r, d->hr_[2 * r], d->hr_[2 * r + 1]);

  int j = 0;
  while (ceilDiv2(d->N_) > j)
  {
    rowPairB(out + s + 0xbc + 17 * j, d->to_[2 * j], d->to_[2 * j + 1]);
    j++;
  }
  const int z1 = s + 17 * ceilDiv2(d->N_) + 0xbb;
  out[z1] = 0;
  if (dsplibs_debug_level > 1)
    dsplibs_debug_printf("#%# Debug: last bit before V.92 info = %d\r\n", z1);

  /* the V.92 info block: sixteen ones, a zero, three preset bytes, then zeros up to the final grid slot z */
  for (i = 0; i < 16; i++)
    out[z1 + 1 + i] = pre[i];
  out[z1 + 1 + 16] = 0;
  for (i = 16; i < 19; i++)
    out[z1 + 1 + 17 + (i - 16)] = pre[i];
  for (i = 0x14; i <= 0x20; i++)
    out[z1 + 1 + i] = 0;

  const int z = s + 17 * ceilDiv2(d->N_) + 0xdd;
  out[z] = 0;
  if (dsplibs_debug_level > 1)
    dsplibs_debug_printf("#%# Debug: last bit after V.92 info = %d, temp calculation = %d\r\n", z, z1 + 1 + 0x20);

  /* CRC, as in the V.90 packer */
  int r[16];
  for (i = 0; i < 16; i++)
    r[i] = 1;
  crcRowsB(r, out, z);
  for (i = 0; i < 16; i++)
    out[z + 1 + i] = (unsigned char)r[i];
  out[z + 17] = 0;
  if (z & 1)
  {
    *len = z + 19;
    out[z + 18] = 0;
  }
  else
  {
    *len = z + 18;
  }
}
