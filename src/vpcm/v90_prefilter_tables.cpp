/**
 * @file v90_prefilter_tables.cpp
 * @brief Constant data of V90PreFilter: the transmit pre-filter coefficient sets, the per-codec reference-loop tables and the hardware-codec database.
 *
 * The class itself (selection of a filter from the measured loop, FIR processing) is declared in v92_echo_canceller.h and defined in the V90PreFilter source
 * files; this file only holds its static tables.  None is written at run time.
 *
 * - `preFilterCoefType1` / `preFilterCoefType2`: 31 filters of 20 float taps each, selected by gain index 0 .. 30.  The two types have the same layout and
 *   different coefficients.
 * - `preFilterCoefType3`: 31 filters of 40 float taps, selected by gain index 20 .. 50 (row = index - 20).
 * - `refLoopsType1` / 2 / 4 / 5 / 6 / 7: reference-loop tables, one per codec family.  A record (V90PreFilterRefLoop, 0x44 bytes in the 32-bit layout) is
 *   {name[32], ref[6], coefType, coefIndex, capability}: `ref` holds the six loop-response measurements (as in V90Phase2Info) that characterise the named
 *   analog front end, `coefType` / `coefIndex` the coefficient set and gain index to use when the measurement matches, and `capability` the V.90 capability
 *   reported for it (0, 1, or 2 = V.90 with EIA-6).  Record names are a prefix (Ascend / Usr), a loop kind (NULL, EIA1 .. EIA7, Chicago, Fountain)
 *   and an optional "Codec2" suffix; they are only labels.  Record counts including the terminator: 23 / 33 / 36 / 36 / 34 / 34.
 * - `dataBase`: 17 {name[32], refLoops} entries indexed by hardware codec type; entry 16 (empty name, NULL table) ends the list. Several codecs share one
 *   table.
 *
 * Values are decimal literals that round-trip as float (9 significant digits).
 */

