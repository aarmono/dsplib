/**
 * @file v92_tx_coding.h
 * @brief Declarations of the three leaf classes of V92Transmitter: V92ConvolutionEncoder, V92Precoder and V92PreFilter.
 *
 * V92Transmitter (pcm_bits_to_symbol.cpp) owns one of each as a heap block, creates them in its constructor and drives them from
 * V92Transmitter::process(): modulus encoder -> V92Precoder::process() -> V92ConvolutionEncoder::process() (three passes per group) ->
 * V92PreFilter::process().  The definitions and the two tables of the convolutional encoder are in v92_tx_coding.cpp.  The i386 layouts are
 * checked by v92_tx_coding_layout.inc (generated by tools/layout_gen.py from layouts/vpcm/v92_tx_coding.layout).
 *
 * V92ConvolutionEncoder: the 4-dimensional trellis (convolutional) encoder of the V.92 / V.34-style shell mapper output.  reset(mode) fills two
 * tables of 64 states x 16 inputs (`next_`: next state, `out_`: the coded bit) for mode 0 (16 states, 2 input bits), 1 (32 states, 3 input bits)
 * or 2 (64 states, 4 input bits); process(a[4]) maps four subset indices to a 6-bit label (inverseMap(): two 2-bit pairs through
 * subsetLabelTable, then cosetMapping4D) and steps the trellis.
 *
 * V92Precoder: the V.92 precoder of the transmitter (a Tomlinson-Harashima style search): for each of four symbols it searches the integer
 * multiples k of the radix m of the candidates u + m * k (u = the data value) for the constellation value whose power after the two feedback FIRs
 * is smallest.
 *
 * V92PreFilter: a FloatFIR followed by a FloatIIR on blocks of 12 samples; a stage whose tap count is 0 is skipped.
 */
#ifndef V92_TX_CODING_H
#define V92_TX_CODING_H

#include "core/dsp_cxx.h"
#include "dsp/dsp_float_filters.h" /* FloatFIR, FloatIIR */
#include "v92_cp.h"                /* V92MappingParams */

/** @brief 4-dimensional trellis encoder: subset indices -> coded bit. */
class V92ConvolutionEncoder
{
public:
  /** @brief Does nothing; reset() initialises the object. */
  V92ConvolutionEncoder();

  /** @brief Does nothing. */
  ~V92ConvolutionEncoder();

  /**
   * @brief Select the trellis and restart it.
   * @param mode  0 = 16 states, 1 = 32 states, 2 = 64 states; any other value builds no table (see process())
   */
  void reset(int mode);

  /**
   * @brief Encode four subset indices and step the trellis.
   * @param a  four subset indices (only their low two bits, plus 2, are used)
   * @return the coded bit; 0 without stepping when mode_ is outside 0 .. 2
   */
  int process(int* a);

  /** @brief Fill next_ / out_ for mode_ 0, 1 or 2 (any other mode: nothing). */
  void makeStateTtransitionTable();

  /**
   * @brief Map four subset indices to the 6-bit coset label.
   * @param a  a[0 .. 3], see process()
   * @return the label cosetMapping4D[...]
   */
  int inverseMap(int* a);

  static int cosetMapping4D[64];   ///< coset label per pair of 3-bit subset labels (index s1 * 8 + s2), 256 bytes
  static int subsetLabelTable[16]; ///< 3-bit subset label per pair of 2-bit indices (index p0 + 4 * p1), 64 bytes

public:
  int32_t mode_;       ///< trellis selector set by reset()
  int32_t state_;      ///< current trellis state
  int32_t out_[1024];  ///< coded bit, out_[(newState << 4) + input]
  int32_t next_[1024]; ///< next state, next_[(state << 4) + input]
};

/** @brief Tomlinson-Harashima style precoder with two feedback FIRs. */
class V92Precoder
{
public:
  /**
   * @brief Create the two feedback FIRs.
   * @param ntaps  tap capacity of each FIR
   * @warning The FIR allocations are not checked; nothing else is initialised here, reset(V92MappingParams*) must run before process().
   */
  explicit V92Precoder(unsigned ntaps);

  /** @brief Destroy and free both FIRs. */
  ~V92Precoder();

  /** @brief Print a debug line (debug level > 1) and reset both FIRs.  No caller in the library. */
  void reset();

  /**
   * @brief Load the constellation data of the mapping parameters and clear the feedback values.
   * @param p  mapping parameters: idxc_, lcp_[6], m_[12], lc_[6]; the tables are borrowed, not copied
   */
  void reset(V92MappingParams* p);

  /**
   * @brief Set the coefficients of the two feedback FIRs.
   * @param c1  coefficients of the first FIR (n1 entries)
   * @param c2  coefficients of the second FIR (n2 entries)
   * @param n1  tap count of the first FIR (0 disables it)
   * @param n2  tap count of the second FIR (0 disables it)
   */
  void setCoefficients(float* c1, float* c2, unsigned n1, unsigned n2);

  /**
   * @brief Precode the four values of one row.
   * @param u      data values; u[row * 4 .. row * 4 + 3] are used
   * @param row    row index (the radix and constellation tables are indexed by row * 4 + j)
   * @param par    parity carried from the previous group
   * @param state  receives the chosen candidate value per symbol; state[0 .. 2] also feed the parity of symbol 3
   * @param out    receives the four precoded values (the best sum of each symbol)
   * @warning row > 2 reads past m_ (12 radices); a symbol with no candidate repeats the previous symbol's result.
   */
  void process(unsigned* u, int row, int par, int* state, float* out);

public:
  uint8_t unk0_[4];    ///< never touched
  uint32_t* idxc_;     ///< V92MappingParams::idxc_ (borrowed)
  uint32_t* lcp_[6];   ///< the six constellation tables (borrowed)
  int32_t m_[12];      ///< radices
  int32_t lc_[6];      ///< constellation sizes
  P02_FloatFIR* fir1_; ///< feedback FIR on the chosen constellation value (heap)
  P02_FloatFIR* fir2_; ///< feedback FIR on the chosen sum (heap)
  float fb1_;          ///< output of fir1_, added to the next candidate
  float fb2_;          ///< output of fir2_, added to the next candidate
  uint32_t n1_;        ///< tap count of fir1_
  uint32_t n2_;        ///< tap count of fir2_
};

/** @brief Pre-filter: FIR then IIR over blocks of 12 samples. */
class V92PreFilter
{
public:
  /**
   * @brief Create the FIR and the IIR.
   * @param ntaps  tap capacity of each filter
   * @warning The allocations are not checked.
   */
  explicit V92PreFilter(unsigned ntaps);

  /** @brief Destroy and free both filters. */
  ~V92PreFilter();

  /** @brief Reset both filters' state. */
  void reset();

  /**
   * @brief Set the coefficients; a stage with a tap count of 0 is skipped by process().
   * @param c1  FIR coefficients (n1 entries)
   * @param c2  IIR coefficients (n2 entries)
   * @param n1  FIR tap count
   * @param n2  IIR tap count
   */
  void setCoefficients(float* c1, float* c2, unsigned n1, unsigned n2);

  /**
   * @brief Filter one block.
   * @param in   12 input samples
   * @param out  12 output samples
   */
  void process(float* in, float* out);

public:
  uint8_t unk0_[4];   ///< never touched
  P02_FloatFIR* fir_; ///< FIR stage (heap)
  P02_FloatIIR* iir_; ///< IIR stage (heap)
  uint32_t nFir_;     ///< FIR tap count
  uint32_t nIir_;     ///< IIR tap count
};

typedef V92ConvolutionEncoder P16_V92ConvolutionEncoder;
typedef V92Precoder P16_V92Precoder;
typedef V92PreFilter P16_V92PreFilter;

#include "v92_tx_coding_layout.inc"

#endif /* V92_TX_CODING_H */
