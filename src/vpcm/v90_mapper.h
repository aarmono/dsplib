/**
 * @file v90_mapper.h
 * @brief Bits <-> constellation-symbol mapper pair of the V.90 / V.92 modem: V90Mapper (transmit), V90Demapper (receive) and V90SignBitsExtractor.
 *
 * Declares three classes, defined in v90_mapper.cpp:
 * - V90Mapper (transmit; a member of V90BitsToSymbol) collects the bits of one frame (w0_ bits), turns them into six constellation digits with a
 *   ModulusEncoder (mixed radix, counts cnt_[0..5]), looks the six digits up in levels_[6][128] (the G.711 code points of a V90MappingParams, decoded
 *   as mu-law or A-law) and gives every level a sign.  Without spectral shaping (K_ == 0) the signs come from a SerialDifferentialEncoder (they are
 *   the first skip_ = 6 - K_ bits of the frame).  With spectral shaping (K_ != 0) the V90SpectralShaper chooses the signs over K_ groups of
 *   spf_ = 6 / K_ symbols.
 * - V90Demapper (receive; a member of V90Demodulator): hardDecision() decides one received sample (the nearest level of the constellation of the
 *   current frame position phase_, from lev_[6][128] = the levels of V90AutoDigitalImpDetector's linear mapping) and queues the digit and the sign
 *   bit.  process() runs a ModulusDecoder over six queued digits and the sign decoder (V90SignBitsExtractor when K_ != 0, a
 *   SerialDifferentialDecoder otherwise) over the queued sign bits: w0_ bits per frame.  linearMappingStudy() and updateConstelation() re-estimate
 *   the levels from the received amplitudes.
 * - V90SignBitsExtractor is the sign-pattern decoder of the demapper's spectral-shaping mode.
 *
 * The member order is the layout the tests probe (layouts/vpcm/v90_mapper.layout, mirrored by v90_mapper_layout.inc, generated by tools/layout_gen.py): do not
 * reorder or resize members.  The prefixed typedefs at the end are used by the generated layout file and by external test harnesses.
 */
#ifndef V90_MAPPER_H
#define V90_MAPPER_H

#include "core/dsp_cxx.h"
#include "dsp/dsp_int_templates.h" /* ParallelDifferentialDecoder<uchar>, SerialDifferentialDecoder<uchar>, SerialDifferentialEncoder<uchar> */
#include "pcm_leaf_classes.h"      /* ModulusEncoder, ModulusDecoder, PcmType */
#include "pcm_parameters.h"        /* V90Parameters */
#include "v92_cp.h"                /* V90MappingParams */
#include "v90_adid.h"              /* V90AutoDigitalImpDetector */
#include "v90_spectral_shaper.h"   /* V90SpectralShaper */

/**
 * @brief Sign-pattern decoder of the demapper's spectral-shaping mode.
 *
 * Takes the n_ = 6 / period_ sign bits of one group, undoes the frame sign pattern selected by action_, runs the parallel and the serial differential
 * decoders and returns n_ - 1 bits (the first decoded bit is dropped).
 */
class V90SignBitsExtractor
{
public:
  /** Sign pattern applied to the n_ bits of a group by applyFrameAction(). */
  enum ACTIONS
  {
    ACTION_KEEP = 0,        ///< copy the bits
    ACTION_NEGATE = 1,      ///< invert every bit
    ACTION_NEGATE_EVEN = 2, ///< invert the even-indexed bits
    ACTION_NEGATE_ODD = 3   ///< invert the odd-indexed bits
  };

  /** @brief Clear the serial decoder state, construct the 6-bit parallel decoder, action_ = 0. */
  V90SignBitsExtractor();
  ~V90SignBitsExtractor();
  /** @brief Start a new stream: period_ = @p period, n_ = 6 / period (0 for period 0), clear the decoders, action_ = @p action. */
  void reset(unsigned period, unsigned action);
  /** @brief Apply sign pattern @p action to n_ bits of @p in, result in @p out.  No caller in the library (process() does the same inline). */
  void applyFrameAction(ACTIONS action, unsigned char* in, unsigned char* out);
  /** @brief Decode one group: @p in holds n_ sign bits, @p out receives n_ - 1 bits.  @p in and @p out must not overlap. */
  void process(unsigned char* in, unsigned char* out);

public:
  unsigned period_;                                ///< number of symbols per sign group's period (K of the mapping parameters); 0 gives n_ = 0
  unsigned n_;                                     ///< bits per group, 6 / period_
  unsigned char buf_[6];                           ///< work buffer for one group
  unsigned char pad0e_[2];                         ///< padding, never accessed
  unsigned action_;                                ///< frame-pattern state: 0 = first group, 1 = second group, other = fixed ACTIONS value
  unsigned char pad14_[4];                         ///< padding, never accessed
  SerialDifferentialDecoder<unsigned char> sde_;   ///< serial differential decoder (applied to odd-indexed bits)
  unsigned char pad19_[3];                         ///< padding, never accessed
  ParallelDifferentialDecoder<unsigned char> pdd_; ///< parallel differential decoder over the group
};

/**
 * @brief Transmit side: bits of a frame to six signed 16-bit symbol levels.
 *
 * process() consumes input bits, one frame of w0_ bits at a time, and appends 6 symbols per frame to the output (fewer for the first frame when a
 * spectral-shaper delay `depth_` is pending).
 */
class V90Mapper
{
public:
  /** @brief Construct for parameter block @p p; allocates the 0x50-byte bit buffer and clears the counters. */
  explicit V90Mapper(V90Parameters* p);
  ~V90Mapper();
  /** @brief Load frame size, K, level tables, encoder moduli and (K != 0) the spectral shaper from @p mp; @p pcm selects mu-law or A-law level decoding. */
  void reset(V90MappingParams* mp, PcmType pcm);
  /** @brief Reload the level tables and encoder moduli from @p mp and reset only the shaper's filter; K, spf and skip are kept. */
  void resetNoSpectral(V90MappingParams* mp, PcmType pcm);
  /**
   * @brief Map @p n input bits (one bit per byte) to symbols.
   * @param in      input bits
   * @param n       number of input bits
   * @param out     output symbol levels, signed 16-bit; 6 per completed frame
   * @param outCnt  receives the number of symbols written
   * @warning @p out is not bounds-checked: it must hold 6 * (n / w0_ + 1) symbols.
   */
  void process(unsigned char* in, unsigned n, short* out, unsigned& outCnt);

public:
  V90Parameters* params_;                        ///< parameter block (not used by the mapper itself)
  unsigned w0_;                                  ///< bits per frame (kBits of the mapping parameters)
  unsigned nbits_;                               ///< bits per frame that go through the modulus encoder, w0_ - skip_
  unsigned skip_;                                ///< leading sign bits of a frame, 6 - K_
  unsigned K_;                                   ///< spectral-shaping groups per frame (0 = no spectral shaping)
  unsigned spf_;                                 ///< symbols per spectral-shaping group, 6 / K_ (0 when K_ == 0)
  unsigned char* buf_;                           ///< bit accumulation buffer, 0x50 bytes, allocated by the constructor
  unsigned fill_;                                ///< number of bits currently in buf_
  unsigned idx_[6];                              ///< constellation digits of the current frame (ModulusEncoder output)
  unsigned short lev_[6];                        ///< unsigned levels of the current frame
  unsigned char sgn_[6];                         ///< signs of the current frame (no-shaping mode), 0 = negative
  unsigned short sym_[6];                        ///< signed symbols of the current frame
  unsigned short levels_[768];                   ///< level tables, 6 constellations x 128 digits, linear PCM values
  unsigned char pad656_[2];                      ///< padding, never accessed
  unsigned cnt_[6];                              ///< constellation sizes (digit counts)
  ModulusEncoder me_;                            ///< mixed-radix encoder over cnt_ and nbits_
  V90SpectralShaper shaper_;                     ///< spectral shaper (K_ != 0)
  unsigned depth_;                               ///< shaper delay in groups still to be skipped at the start of a stream
  SerialDifferentialEncoder<unsigned char> sde_; ///< sign differential encoder (K_ == 0)
  unsigned char pad6fd_[3];                      ///< padding, never accessed
  unsigned z700_;                                ///< cleared by reset() / resetNoSpectral(), otherwise unused
};

/**
 * @brief Receive side: hard decisions on received samples, then digits and sign bits to data bits.
 *
 * hardDecision() queues one digit and one sign bit per sample (wr_ entries, at most cap_); process() consumes them six at a time (rd_) and writes
 * w0_ data bits per frame.  The level estimator (linearMappingStudy() / updateConstelation()) follows the detector's cumulative sums.
 */
class V90Demapper
{
public:
  /**
   * @brief Construct a demapper with room for @p cap queued decisions.
   * @param cap   capacity of the digit and bit queues
   * @param p     parameter block (debug parameters are read from it)
   * @param adid  auto-digital-impairment detector whose linear mapping tables are read and whose cumulative arrays are written
   * @warning the two sysdep_malloc() results are not checked.
   */
  V90Demapper(unsigned cap, V90Parameters* p, V90AutoDigitalImpDetector* adid);
  /** @brief Print the pending error histogram when enabled and free the queues. */
  ~V90Demapper();
  /** @brief Restart the linear-mapping study: clear the cumulative arrays and counters and set the study length to @p len decisions. */
  void resetLinearMappStudy(unsigned len);
  /** @brief Load frame size, K, levels, decoder moduli from @p mp, empty the queues and clear the histogram and study state. */
  void reset(V90MappingParams* mp);
  /** @brief Reload frame size, levels and decoder moduli from @p mp; K, spf and skip are kept and the queues are not touched. */
  void resetNoSpectral(V90MappingParams* mp);
  /** @brief Advance the frame position (0..5) by one symbol without making a decision. */
  void incrementRBSFramePosition();
  /** @brief Print the per-level error histogram (when all six constellations are non-empty), clear it and count the print. */
  void printErrorHistogramAndReset();
  /** @brief Decide sample @p x: queue its digit and sign bit and return the chosen signed level (0 when the queue is full). */
  short hardDecision(short x);
  /** @brief Recompute the levels from the detector's cumulative sums (see rebuildLevels in v90_mapper.cpp). */
  void updateConstelation();
  /** @brief Feed the pair of samples (@p a, @p b) of the linear-mapping study; at the end of a study round rebuild the levels and clear the sums. */
  void linearMappingStudy(short a, short b);
  /**
   * @brief Decode the queued decisions, six at a time.
   * @param out     receives the data bits, w0_ per frame
   * @param outCnt  receives the number of bits written
   * @return 0 when fewer than six decisions are queued (outCnt = 0), otherwise 1 (outCnt may still be 0)
   * @warning @p out is not bounds-checked.
   */
  unsigned process(unsigned char* out, unsigned& outCnt);

public:
  V90Parameters* params_;                        ///< parameter block (debug parameters)
  unsigned w0_;                                  ///< bits per frame
  unsigned nbits_;                               ///< bits per frame that go through the modulus decoder, w0_ - skip_
  unsigned skip_;                                ///< sign bits per frame, 6 - K_
  unsigned K_;                                   ///< spectral-shaping groups per frame (0 = none)
  unsigned spf_;                                 ///< symbols per group, 6 / K_ (not reset when K_ == 0)
  unsigned phase_;                               ///< position in the 6-symbol frame, selects the constellation
  unsigned* digits_;                             ///< queued constellation digits, cap_ entries
  unsigned char* bits_;                          ///< queued sign bits, cap_ entries (1 = non-negative sample)
  unsigned cap_;                                 ///< queue capacity
  unsigned rd_;                                  ///< read index of the queues
  unsigned wr_;                                  ///< write index of the queues
  short lev_[768];                               ///< decision levels, 6 constellations x 128, descending within a constellation
  unsigned cnt_[6];                              ///< constellation sizes
  ModulusDecoder md_;                            ///< mixed-radix decoder over cnt_ and nbits_
  SerialDifferentialDecoder<unsigned char> sdd_; ///< sign differential decoder (K_ == 0)
  unsigned char pad665_[3];                      ///< padding, never accessed
  V90SignBitsExtractor sbe_;                     ///< sign decoder (K_ != 0)
  unsigned errSum_[768];                         ///< error histogram: summed absolute error per level
  unsigned errCnt_[768];                         ///< error histogram: decisions per level
  unsigned histNo_;                              ///< number of histogram prints so far
  unsigned delay_;                               ///< decisions to ignore before the histogram starts counting
  unsigned integ_;                               ///< decisions counted in the current histogram
  unsigned short studyIter_;                     ///< completed study rounds
  unsigned char pad1e9e_[2];                     ///< padding, never accessed
  V90AutoDigitalImpDetector* adid_;              ///< detector supplying the linear mappings and the cumulative arrays
  unsigned short studyDone_;                     ///< set when a study round completes (constellation updated); read by V90Equalizer::process
  unsigned short study2Done_;                    ///< set when the second study round completes; read by V90Equalizer::process
  unsigned studyLen_;                            ///< decisions per study round
  unsigned short prevIdx_;                       ///< level index of the last hard decision (study input)
  unsigned short set_;                           ///< constellation (frame position) of the last hard decision (study input)
  unsigned studyCnt_;                            ///< decisions seen in the current study round
  unsigned short linMapStudyOn_; ///< nonzero while the linear-mapping study runs; cleared by reset(), set and cleared by the demodulators / equalizer
  unsigned char pad1eb6_[2];     ///< padding, never accessed
};

typedef V90SignBitsExtractor P28_V90SignBitsExtractor;
typedef V90Mapper P28_V90Mapper;
typedef V90Demapper P28_V90Demapper;

#pragma GCC diagnostic ignored "-Winvalid-offsetof"
#include "v90_mapper_layout.inc"

#endif /* V90_MAPPER_H */
