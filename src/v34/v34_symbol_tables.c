/**
 * @file v34_symbol_tables.c
 * @brief Data tables of the V.34 symbol path: transmit points, bit masks, FSK detector filters, rate scale rows and tone-detector coefficients.
 *
 * Twenty tables of plain 16 / 32-bit data, width-exact on any host.  Readers:
 *   - getFrame() (v34_tx_symbol.c): lsbMask (ushort[17]), a mask of the k low bits.
 *   - txmitdibit() / txmitquadbit() (v34_tx_symbol.c, and the V.90 / K56Flex phase code in src/vpcm): vect4 and vect16, int32 packed I/Q points,
 *     dword = (hi16 << 16) + lo16, as handed to the modulator.
 *   - fskdetect() (v34_detectors.c): intcoef1..3 (short[12]) and fsklpfcoeff600 (short[80]).
 *   - initdigital() / setfinalrate() (v34_handshake_helpers.c) and the probing selector (v34_probe_select.c): scale2400..scale3429 and the
 *     tone-detector tables c1600..c2000.
 * The tone-detector tables c1200_ / c2400_ and the filter taps bpv22high / bpv22low used by the same functions are in v34_frame_tables.c, rxvect4
 * and gInvertPat in v34_init_tables.c.  The cosine table `costbl` read by dftupdate() and receiver() is the V.8 table v8_costbl (byte-identical,
 * 256 entries; the macro `costbl` of v34_symbol_tables.h names it); it is not defined again.
 *
 * Structure of the data (checked by script when the tables were extracted):
 *   - lsbMask[k] == (1 << k) - 1 for k = 0..15, lsbMask[16] == 0xffff.
 *   - vect4 holds four points (4579,4579) (4579,-4579) (-4579,-4579) (-4579,4579) as (lo16, hi16) halves; vect16 holds 16 distinct points whose halves
 *     take only {-6144, -2048, 2048, 6144} (a 4x4 grid).  txmitquadbit()'s index is always 0..15, so vect16 is never over-read.
 *   - intcoef3 is intcoef1 reversed, intcoef2 is even-symmetric; sums 21859 / 21872 / 21859.  fsklpfcoeff600 is even-symmetric, all positive
 *     (22..1365), sum 49120.
 *   - scaleNNNN: two rows of 14 shorts, indexed [rateIndex + 14 * row - 1]; the largest entry of all five is 4579; each row has zeros at its start and/or end.
 *     The two out-of-range reads initdigital() can make (index -1 and 28) fall outside the 56-byte table (the reference build reads zero padding
 *     there); the port does not reproduce those bytes.
 *   - c1600..c2000: c[0..3] == 0, c[5] == c[7] == 15735; with r^2 = c[5] / 16384 and -c[k] = 2 r cos(2 pi f / 9600), the frequencies implied by c[4] and
 *     c[6] are (name - 2, name + 2) Hz for every table except c1959, where the two are in the opposite order (c[6] - c[4] = -81 instead of +73..+81);
 *     kept as found.  c1200_ and c2400_ have c[4] == c[6] and r^2 = 15993 / 16384.
 *
 * This file is generated by a table-extraction script that is not part of the library; only its comments were edited by hand.
 */
